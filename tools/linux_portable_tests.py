#!/usr/bin/env python3
"""Packs the portable subset of the Linux test suite so it runs in another distribution's container.

tools/linux_portable_tests.txt names ctest cases; this reads their commands, environments, timeouts and skip codes from
a configured and built Linux build directory (`ctest --show-only=json-v1`) and writes a bundle:

  OUTPUT/build/...       the executables the cases run, in their build directory layout
  OUTPUT/portable.sh     a POSIX sh script that runs every case the way ctest would (the same environment, working
                         directory, timeout and skip code) and prints PASS, SKIP or FAIL per case

The bundle refers to /mc/bundle (itself) and /mc/src (the repository, read-only: the fixtures, the TLS smoke script). Mount
them there, then `sh /mc/bundle/portable.sh`. Nothing but coreutils (env, timeout) and sh is needed, so the same script runs
on glibc distributions and on NixOS. The registry's MAICORD_TEST_FONT_SET and MAICORD_TEST_SPELL_SET (which make the font
and dictionary assertions strict for the Ubuntu packages) are dropped: the assertions then hold on any host.

  linux_portable_tests.py --build ~/mc-build --output DIR [--sections default,wayland,gpu] [--timeout-scale 3]

The bundle also holds the build's client as OUTPUT/MaiCord when there is one: tools/test_linux_distros.sh starts it on
headless sway in the distributions that install sway.

The executables are the glibc build's; tools/test_linux_distros.sh retargets its copy of them for the musl containers
(tools/retarget_libc.py --tree), so the one build runs in Alpine, Void and Chimera as it runs in glibc distributions.
"""
import argparse
import json
import os
import pathlib
import re
import shlex
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SELECTION = ROOT / 'tools' / 'linux_portable_tests.txt'
BUNDLE = '/mc/bundle'
SOURCE = '/mc/src'
DROPPED = ('MAICORD_TEST_FONT_SET', 'MAICORD_TEST_SPELL_SET')

PREAMBLE = r'''#!/bin/sh
# Generated by tools/linux_portable_tests.py; run as `sh /mc/bundle/portable.sh` with /mc/bundle and /mc/src mounted.
logs=/mc/bundle/logs
mkdir -p "$logs"
passed=0
failed=0
skipped=0
echo "host: $( [ -r /etc/os-release ] && . /etc/os-release; echo "${PRETTY_NAME:-no os-release}"), $(uname -srm), libc $(getconf GNU_LIBC_VERSION 2>/dev/null || ls /lib/ld-musl-* 2>/dev/null | head -n 1 || echo unknown)"

# SECTIONS names the sections that run (default: all of them); a distribution without a Mesa EGL leaves out "gpu".
# run SECTION NAME TIMEOUT SKIP-CODE WORKING-DIRECTORY VAR=value... COMMAND ARGUMENT...
run() {
    section=$1
    case " ${SECTIONS:-default wayland gpu} " in *" $section "*) ;; *) return 0 ;; esac
    name=$2
    limit=$3
    skip=$4
    dir=$5
    shift 5
    start=$(date +%s)
    ( cd "$dir" && exec timeout -k 5 "$limit" env "$@" ) >"$logs/$name.log" 2>&1
    code=$?
    seconds=$(( $(date +%s) - start ))
    if [ "$code" -eq 0 ]; then
        passed=$((passed + 1))
        echo "PASS $name (${seconds}s)"
    elif [ -n "$skip" ] && [ "$code" -eq "$skip" ]; then
        skipped=$((skipped + 1))
        echo "SKIP $name (${seconds}s)"
    else
        failed=$((failed + 1))
        echo "FAIL $name (exit $code, ${seconds}s)"
        tail -n 25 "$logs/$name.log" | sed 's/^/    | /'
    fi
}

'''

EPILOGUE = r'''
echo "$passed passed, $skipped skipped, $failed failed"
[ "$failed" -eq 0 ]
'''


def selection(sections):
    """(section, name) of the chosen cases, in the file's order."""
    chosen = []
    section = 'default'
    for line in SELECTION.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        if line.startswith('[') and line.endswith(']'):
            section = line[1:-1]
            continue
        if section in sections:
            chosen.append((section, line))
    return chosen


def remapper(build, source):
    patterns = [(re.compile(re.escape(str(build)) + r'(?=/|$)'), BUNDLE + '/build'),
                (re.compile(re.escape(str(source)) + r'(?=/|$)'), SOURCE)]

    def remap(text):
        for pattern, replacement in patterns:
            text = pattern.sub(replacement, text)
        return text
    return remap


def cache_value(build, name):
    for line in (build / 'CMakeCache.txt').read_text().splitlines():
        if line.startswith(name + ':'):
            return line.split('=', 1)[1]
    raise SystemExit('error: %s has no %s' % (build / 'CMakeCache.txt', name))


def case_command(test, remap, strict):
    """The environment (as `env` takes it: `-u NAME` options, which GNU, busybox and BSD env accept, then NAME=value)
    and the command of a ctest case."""
    command = list(test['command'])
    operations = []  # ('set', name, value) or ('unset', name), in the order ctest and cmake -E env apply them
    for property_ in test.get('properties', []):
        if property_['name'] == 'ENVIRONMENT':
            operations += [('set',) + tuple(item.split('=', 1)) for item in property_['value']]
    # cmake -E env A=B --unset=C program arguments... (maicord_add_tests ENV)
    if len(command) >= 3 and os.path.basename(command[0]) == 'cmake' and command[1:3] == ['-E', 'env']:
        command = command[3:]
        while command:
            if command[0].startswith('--unset='):
                operations.append(('unset', command.pop(0)[len('--unset='):]))
            elif re.match(r'^[A-Za-z_][A-Za-z0-9_]*=', command[0]):
                operations.append(('set',) + tuple(command.pop(0).split('=', 1)))
            else:
                break
    if command and command[0] in ('/usr/bin/sh', '/bin/sh'):
        command[0] = 'sh'
    final = {}
    for operation in operations:
        final[operation[1]] = operation[2] if operation[0] == 'set' else None
    if not strict:
        for name in DROPPED:
            final.pop(name, None)
    environment = [item for name, value in final.items() if value is None for item in ('-u', name)]
    environment += ['%s=%s' % (name, remap(value)) for name, value in final.items() if value is not None]
    return environment, [remap(item) for item in command]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--build', required=True, type=pathlib.Path)
    parser.add_argument('--output', required=True, type=pathlib.Path)
    parser.add_argument('--sections', default='default,wayland,gpu', help='comma separated: default, wayland, gpu')
    parser.add_argument('--timeout-scale', type=int, default=3)
    parser.add_argument('--strict-sets', action='store_true', help='keep MAICORD_TEST_FONT_SET and MAICORD_TEST_SPELL_SET')
    arguments = parser.parse_args()

    build = arguments.build.resolve()
    source = pathlib.Path(cache_value(build, 'CMAKE_HOME_DIRECTORY')).resolve()
    listing = subprocess.run(['ctest', '--test-dir', str(build), '--show-only=json-v1'], check=True,
                             stdout=subprocess.PIPE, text=True).stdout
    tests = {test['name']: test for test in json.loads(listing)['tests']}
    names = selection(set(arguments.sections.split(',')))
    missing = [name for _, name in names if name not in tests]
    if missing:
        raise SystemExit('error: tools/linux_portable_tests.txt names cases the build does not register: ' + ', '.join(missing))

    remap = remapper(build, source)
    output = arguments.output
    shutil.rmtree(output, ignore_errors=True)
    (output / 'build').mkdir(parents=True)
    script = [PREAMBLE]
    copied = set()
    for section, name in names:
        test = tests[name]
        environment, command = case_command(test, remap, arguments.strict_sets)
        properties = {item['name']: item['value'] for item in test.get('properties', [])}
        for token in test['command']:
            path = pathlib.Path(token)
            if path.is_absolute() and path.exists() and path.is_file() and build in path.parents and token not in copied:
                target = output / 'build' / path.relative_to(build)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, target)
                copied.add(token)
        limit = int(float(properties.get('TIMEOUT', 20)) * arguments.timeout_scale)
        skip = properties.get('SKIP_RETURN_CODE', '')
        directory = remap(properties.get('WORKING_DIRECTORY', str(build)))
        script.append('run %s %s %d %s %s %s\n' % (section, shlex.quote(name), limit, shlex.quote(str(skip)),
                                                    shlex.quote(directory),
                                                    ' '.join(shlex.quote(item) for item in environment + command)))
    script.append(EPILOGUE)
    if (build / 'MaiCord').is_file():
        shutil.copy2(build / 'MaiCord', output / 'MaiCord')
    (output / 'portable.sh').write_text(''.join(script), newline='\n')
    sizes = sum(path.stat().st_size for path in (output / 'build').rglob('*') if path.is_file())
    print('%d cases, %d files (%.1f MiB) in %s' % (len(names), len(copied), sizes / 1048576, output))


if __name__ == '__main__':
    sys.exit(main())
