"""Generate the AV1 live-decode GPU fixture (needs PyAV with libsvtav1 and libdav1d).

Encodes six synthetic 256x64 frames of flat 32x32 blocks losslessly with
SVT-AV1 (two tile columns, random-access GOP: hidden frames and
show_existing_frame), checks that dav1d decodes them bit-exactly, and writes
each temporal unit as Discord's depacketizer delivers it: no temporal
delimiter, every OBU but the last with a minimal obu_size, the last without.
A 10-bit key unit checks that the decoder refuses what it cannot output, and
a 33-frame five-level hierarchical GOP at 64x64 needs more distinct
references than the decoder's initial surface pool holds.
The pixel formula is repeated in tests/av1_stream_gpu_test.cpp.

    python tools/av1_stream_fixture.py tests/data/av1_stream_vectors.hpp
"""
import argparse
from fractions import Fraction
from pathlib import Path

import av
import numpy as np
from av.codec import CodecContext

WIDTH, HEIGHT, FRAMES = 256, 64, 6


def block_values(index, k):
    return ((40 + 23 * k + 11 * index) % 220 + 16, (60 + 37 * k + 5 * index) % 200 + 28,
            (90 + 53 * k + 7 * index) % 200 + 28)


def planes(index):
    y = np.zeros((HEIGHT, WIDTH), np.uint8)
    u = np.zeros((HEIGHT // 2, WIDTH // 2), np.uint8)
    v = np.zeros((HEIGHT // 2, WIDTH // 2), np.uint8)
    for by in range(HEIGHT // 32):
        for bx in range(WIDTH // 32):
            luma, cb, cr = block_values(index, by * (WIDTH // 32) + bx)
            y[by * 32:by * 32 + 32, bx * 32:bx * 32 + 32] = luma
            u[by * 16:by * 16 + 16, bx * 16:bx * 16 + 16] = cb
            v[by * 16:by * 16 + 16, bx * 16:bx * 16 + 16] = cr
    return y, u, v


def encode(frames=FRAMES, pixel_format='yuv420p', size=(WIDTH, HEIGHT),
           parameters='lossless=1:tile-columns=1'):
    context = CodecContext.create('libsvtav1', 'w')
    context.width, context.height, context.pix_fmt = size[0], size[1], pixel_format
    context.time_base, context.framerate = Fraction(1, 30), 30
    context.options = {'svtav1-params': parameters}
    units = []
    for index in range(frames):
        frame = av.VideoFrame(size[0], size[1], pixel_format)
        for number, (plane, values) in enumerate(zip(frame.planes, planes(index))):
            values = values[:size[1] >> (number > 0), :size[0] >> (number > 0)]
            sample = np.uint8 if pixel_format == 'yuv420p' else np.uint16
            view = np.frombuffer(plane, sample).reshape(-1, plane.line_size // np.dtype(sample).itemsize)
            view[:values.shape[0], :values.shape[1]] = values
        frame.pts = index
        units += [bytes(packet) for packet in context.encode(frame)]
    units += [bytes(packet) for packet in context.encode(None)]
    return units


def verify(units):
    decoder = CodecContext.create('libdav1d', 'r')
    frames = [f for unit in units for f in decoder.decode(av.Packet(unit))] + list(decoder.decode(None))
    assert len(frames) == FRAMES, len(frames)
    for index, frame in enumerate(frames):
        for plane, expected in zip(frame.planes, planes(index)):
            got = np.frombuffer(plane, np.uint8).reshape(-1, plane.line_size)[:expected.shape[0], :expected.shape[1]]
            assert (got == expected).all(), f'frame {index} is not lossless'


def leb128(value):
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        out.append(byte | (0x80 if value else 0))
        if not value:
            return bytes(out)


def obus(unit):
    offset = 0
    while offset < len(unit):
        header = unit[offset]
        start = offset + 1 + ((header >> 2) & 1)
        size, at, shift = 0, start, 0
        while True:
            byte = unit[at]
            at += 1
            size |= (byte & 0x7F) << shift
            shift += 7
            if not byte & 0x80:
                break
        yield unit[offset:start], unit[at:at + size]
        offset = at + size


def depacketized(unit):
    kept = [(h, p) for h, p in obus(unit) if (h[0] >> 3) & 15 not in (2, 8, 15)]
    out = bytearray()
    for index, (header, payload) in enumerate(kept):
        if index + 1 < len(kept):
            out += bytes([header[0] | 2]) + header[1:] + leb128(len(payload)) + payload
        else:
            out += bytes([header[0] & ~2]) + header[1:] + payload
    return bytes(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    units = encode()
    verify(units)
    frames = [depacketized(unit) for unit in units]
    lines = ['// Generated by tools/av1_stream_fixture.py: SVT-AV1 lossless encode of synthetic blocks.',
             f'constexpr u32 kAv1FixtureWidth = {WIDTH}, kAv1FixtureHeight = {HEIGHT}, '
             f'kAv1FixtureFrames = {FRAMES};',
             'constexpr const char* av1_fixture_units[]{']
    lines += [f'    "{frame.hex()}",' for frame in frames]
    lines.append('};')
    ten_bit = depacketized(encode(1, 'yuv420p10le')[0])
    lines.append(f'constexpr const char* av1_fixture_ten_bit = "{ten_bit.hex()}";')
    deep = [depacketized(unit) for unit in encode(33, size=(64, 64), parameters='crf=50:hierarchical-levels=5')]
    lines.append('constexpr const char* av1_fixture_deep_units[]{')
    lines += [f'    "{unit.hex()}",' for unit in deep]
    lines.append('};')
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'Generated {len(frames)} temporal units ({sum(map(len, frames))} bytes): {args.output}')


if __name__ == '__main__':
    main()
