#!/usr/bin/env python3
"""Deflate-pack fxc /Fh bytecode arrays into one generated include.

Usage: pack_shader_bytecode.py OUTPUT NAME=HEADER ...
Entries keep the argument order; src/render/shader_bytecode.cpp checks that it
matches ShaderId. A sparse wide-COLR variant can share the normal stream.
Each shader still needs one inflate and one output buffer on use.
"""
import pathlib
import re
import sys
import zlib


def read_bytecode(path):
    text = pathlib.Path(path).read_text()
    start = text.index("const BYTE ")
    body = re.search(r"\{(.*?)\};", text[start:], re.S).group(1)
    data = bytes(int(v) for v in re.findall(r"\d+", body))
    if data[:4] != b"DXBC":
        raise SystemExit(f"{path}: not DXBC bytecode")
    return data


def pack(data):
    best = None
    for mem in (8, 9):
        for strategy in (zlib.Z_DEFAULT_STRATEGY, zlib.Z_FILTERED):
            c = zlib.compressobj(9, zlib.DEFLATED, 15, mem, strategy)
            out = c.compress(data) + c.flush()
            if best is None or len(out) < len(best):
                best = out
    assert zlib.decompress(best) == data
    return best


PATCH_FLAG = 1 << 31


def generate(entries):
    names = [name for name, _ in entries]
    if len(set(names)) != len(names):
        raise ValueError("Duplicate shader name")
    compressed = [pack(data) for _, data in entries]
    patches, shared_index, base_index = [], None, None
    if "colr_compute" in names and "colr_wide_compute" in names:
        base_index = names.index("colr_compute")
        target = names.index("colr_wide_compute")
        base, wide = entries[base_index][1], entries[target][1]
        if base_index < target and len(base) == len(wide):
            changes = [(offset, value) for offset, (before, value) in enumerate(zip(base, wide))
                       if before != value]
            # Three bytes per patch plus a conservative metadata allowance.
            # A future shader with a different layout keeps its own stream.
            if (all(offset < 65536 for offset, _ in changes) and
                    3 * len(changes) + 16 < len(compressed[target])):
                patches, shared_index = changes, target
    blob, rows, names, maximum = bytearray(), [], [], 0
    for index, (name, data) in enumerate(entries):
        if index == shared_index:
            offset, count, _ = rows[base_index]
            rows.append((offset | (PATCH_FLAG if patches else 0), count, len(data)))
        else:
            packed = compressed[index]
            if len(blob) + len(packed) >= PATCH_FLAG:
                raise ValueError("Shader pack exceeds offset capacity")
            rows.append((len(blob), len(packed), len(data)))
            blob += packed
        names.append(name)
        maximum = max(maximum, len(data))
    if (patches != sorted(set(patches)) or len({offset for offset, _ in patches}) != len(patches) or
            any(not 0 <= value <= 255 for _, value in patches)):
        raise ValueError("Invalid sparse shader patch")
    # Reconstruct every shader, including the DXBC checksum, before publication.
    for (_, expected), (offset, count, raw_bytes) in zip(entries, rows):
        first = offset & ~PATCH_FLAG
        actual = bytearray(zlib.decompress(blob[first:first + count]))
        if offset & PATCH_FLAG:
            for at, value in patches:
                if at >= raw_bytes:
                    raise ValueError("Shader patch exceeds output")
                actual[at] = value
        if len(actual) != raw_bytes or actual != expected:
            raise ValueError("Shader reconstruction changed bytecode")
    lines = ["// Generated by tools/pack_shader_bytecode.py; do not edit.",
             f"constexpr u32 kShaderMaximumBytes={maximum};",
             f"constexpr u32 kShaderPatchFlag={PATCH_FLAG}u;",
             f"constexpr u32 kShaderPatchCount={len(patches)};",
             "constexpr u16 kShaderPatchOffsets[]={" + ",".join(str(at) for at, _ in patches or [(0, 0)]) + "};",
             "constexpr u8 kShaderPatchValues[]={" + ",".join(str(value) for _, value in patches or [(0, 0)]) + "};",
             "constexpr PackedShader kShaders[]={"]
    lines += [f"{{{o},{p},{r}}}, // {n}" for (o, p, r), n in zip(rows, names)]
    lines.append("};")
    for index, name in enumerate(names):
        lines.append(f"constexpr u32 kShaderIndex_{name}={index};")
    # Keep the measured native image layout without another buffer or copy.
    # Recheck private image pages when the pack or surrounding data changes.
    lines.append("alignas(128) constexpr u8 kShaderPacked[]={")
    for i in range(0, len(blob), 40):
        lines.append(",".join(str(b) for b in blob[i:i + 40]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    output = pathlib.Path(sys.argv[1])
    entries = []
    for argument in sys.argv[2:]:
        name, path = argument.split("=", 1)
        entries.append((name, read_bytecode(path)))
    text = generate(entries)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != text:
        output.write_text(text, newline="\n")


if __name__ == "__main__":
    main()
