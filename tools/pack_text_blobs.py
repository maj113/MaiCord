#!/usr/bin/env python3
"""Deflate-pack cold text blobs (JSON documents, page fragments) that their owner inflates on first use.

Usage: pack_text_blobs.py OUTPUT_DIRECTORY NAME=FILE...

Per blob (NAME in CamelCase) this writes `<name>_pack.inc` (`constexpr u32 k<NAME>Bytes` and the `#embed` of the zlib
stream `k<NAME>Packed`) and `<name>_packed.bin` beside it, <name> being NAME in snake_case. The owner inflates the
stream once through include/maicord/media/compression/inflated_block.hpp (private pages kept for the process
lifetime), so views into the inflated text stay valid. The raw bytes are exactly the file's.
"""
import pathlib
import re
import sys

import optimal_deflate
from font_reference.embed_fixture import embed_arrays, write_if_changed


def main():
    directory = pathlib.Path(sys.argv[1])
    directory.mkdir(parents=True, exist_ok=True)
    for argument in sys.argv[2:]:
        name, _, file = argument.partition("=")
        if not name.isidentifier() or not file:
            raise SystemExit(f"expected NAME=FILE, got {argument!r}")
        data = pathlib.Path(file).read_bytes()
        if not data:
            raise SystemExit(f"{file}: empty")
        stem = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
        write_if_changed(directory / f"{stem}_packed.bin", optimal_deflate.zlib_stream(data))
        text = (f"// Generated by tools/pack_text_blobs.py from {pathlib.Path(file).name}; do not edit.\n"
                f"constexpr u32 k{name}Bytes={len(data)};\n"
                + embed_arrays([(f"constexpr u8 k{name}Packed[]", f"{stem}_packed.bin")]))
        write_if_changed(directory / f"{stem}_pack.inc", text.encode("utf-8"))


if __name__ == "__main__":
    main()
