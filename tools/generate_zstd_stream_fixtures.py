"""Writes tests/zstd_stream_fixtures.inc: reference-encoder zstd streams of
deterministic synthetic text (Python 3.14 compression.zstd).

Usage: python -I tools/generate_zstd_stream_fixtures.py tests/zstd_stream_fixtures.inc
The text generator is mirrored in tests/zstd_stream.cpp (fixture_text)."""
import sys
from compression import zstd
from compression.zstd import ZstdCompressor, CompressionParameter as P

MASK = (1 << 64) - 1
WORDS = [b"alpha", b"stream", b"window", b"block", b"literal", b"offset", b"match", b"sequence",
         b"\"id\":\"", b"\",\"name\":\"", b"{\"op\":0,\"d\":{", b"}}", b"guild", b"channel",
         b"message", b"\\u00e9", b"\n", b" ", b"0", b"[", b"]", b",", b":", b"true", b"null"]


def text(seed, size, mode):
    if mode == 5:  # periodic: one 3000-byte text repeated
        base = text(seed, 3000, 0)
        return (base * (size // 3000 + 1))[:size]
    state = (seed * 0x9E3779B97F4A7C15 + 1) & MASK
    out = bytearray()

    def nxt():
        nonlocal state
        state ^= state >> 12
        state ^= (state << 25) & MASK
        state ^= state >> 27
        return (state * 2685821657736338717) & MASK

    while len(out) < size:
        r = nxt()
        if mode == 1:  # repetitive: long runs of one word
            word = WORDS[(r >> 40) % 4]
            out += word * (1 + (r >> 20) % 12)
        elif mode == 2:  # incompressible-ish bytes
            out += (r >> 8).to_bytes(7, "little")
        elif mode == 3:  # one byte
            out += b"z" * 64
        elif mode == 4:  # a small alphabet
            out += bytes([97 + (r >> 60) % 5, 97 + (r >> 50) % 3])
        elif mode == 6:  # random letters
            out += bytes([97 + (r >> 59) % 26, 97 + (r >> 40) % 26, 32 if (r >> 30) % 5 == 0 else 97 + (r >> 20) % 26])
        else:
            pick = (r >> 32) % (len(WORDS) + 3)
            if pick < len(WORDS):
                out += WORDS[pick]
            else:
                out += str(r % 1000003).encode()
    return bytes(out[:size])


def stream(level, window_log, checksum, messages):
    options = {P.compression_level: level, P.window_log: window_log, P.checksum_flag: checksum}
    c = ZstdCompressor(options=options)
    chunks = []
    for seed, size, mode in messages:
        chunks.append(c.compress(text(seed, size, mode), mode=ZstdCompressor.FLUSH_BLOCK))
    return chunks


def end_frame(level, window_log, checksum, messages):
    options = {P.compression_level: level, P.window_log: window_log, P.checksum_flag: checksum}
    c = ZstdCompressor(options=options)
    chunks = []
    for i, (seed, size, mode) in enumerate(messages):
        chunks.append(c.compress(text(seed, size, mode), mode=ZstdCompressor.FLUSH_FRAME))
    return chunks


MESSAGES = {
    "gateway_like": (3, 16, 0, [(1, 300, 0), (2, 3000, 0), (3, 40, 0), (4, 3000, 6), (5, 140000, 5), (6, 1200, 0)]),
    "small_window_checksum": (19, 10, 1, [(11, 1500, 0), (12, 1800, 0), (13, 64, 0), (14, 500, 2)]),
    "fast_raw": (-5, 12, 0, [(21, 1500, 0), (22, 300, 2), (23, 1500, 1)]),
    "runs": (3, 17, 0, [(61, 300000, 3), (62, 3000, 4), (63, 2000, 1)]),
    "large_window": (1, 20, 0, [(41, 800, 0), (42, 1000, 0)]),
}
cases = [(name, stream(*args)) for name, args in MESSAGES.items()]
cases.append(("frames", end_frame(9, 15, 1, [(31, 1500, 0), (32, 400, 0), (33, 0, 0)])))
messages_of = {name: args[3] for name, args in MESSAGES.items()}
messages_of["frames"] = [(31, 1500, 0), (32, 400, 0), (33, 0, 0)]
# One-shot frame with a content size (single segment) and a checksum.
single = zstd.compress(text(51, 1200, 0), options={P.compression_level: 7, P.checksum_flag: 1})

out = sys.stdout if len(sys.argv) < 2 else open(sys.argv[1], "w", newline="\n")
out.write("// Generated by tools/generate_zstd_stream_fixtures.py (zstd 1.5.7); synthetic data only.\n")
total = 0


def emit(name, data):
    global total
    total += len(data)
    out.write(f"constexpr u8 {name}[] = {{")
    for i, b in enumerate(data):
        if i % 24 == 0:
            out.write("\n   ")
        out.write(f" 0x{b:02x},")
    out.write("\n};\n")


for name, chunks in cases:
    for i, chunk in enumerate(chunks):
        emit(f"k_{name}_{i}", chunk)
emit("k_single_frame", single)
out.write("struct FixtureMessage { u32 seed, size, mode; const u8* data; u32 bytes; };\n")
for name, chunks in cases:
    out.write(f"constexpr FixtureMessage k_{name}[] = {{\n")
    for i, (seed, size, mode) in enumerate(messages_of[name]):
        out.write(f"    {{{seed}, {size}, {mode}, k_{name}_{i}, sizeof(k_{name}_{i})}},\n")
    out.write("};\n")
sys.stderr.write(f"fixture bytes {total}\n")
