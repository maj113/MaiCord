SHA='b194abe1561995223482dbad51c180146920dc2f637e74d01e07a388308791fb'


def vector(b):
    n=len(b)
    return (bytes([n]) if n<64 else (n|(0x4000 if n<16384 else 0x80000000)).to_bytes(2 if n<16384 else 4,'big'))+b


def framed(label,content):
    return vector(b'MLS 1.0 '+label)+vector(content)


class Reader:
    def __init__(self,b): self.b=b;self.p=0
    def take(self,n):
        assert self.p+n<=len(self.b)
        v=self.b[self.p:self.p+n];self.p+=n;return v
    def num(self,n): return int.from_bytes(self.take(n),'big')
    def vec(self):
        b=self.num(1);p=b>>6;assert p!=3
        n=b&63
        for _ in range((1<<p)-1):n=(n<<8)|self.num(1)
        assert p==0 or n>=(64 if p==1 else 16384)
        return self.take(n)


def extensions(r):
    b=r.vec();q=Reader(b)
    while q.p<len(b):q.num(2);q.vec()
    return b


def leaf(r):
    start=r.p;ek=r.vec();sk=r.vec();ctype=r.take(2);identity=certs=b''
    if ctype==b'\0\1':identity=r.vec()
    elif ctype==b'\0\2':
        certs=r.vec();q=Reader(certs)
        while q.p<len(certs):q.vec()
    else:raise ValueError('unknown credential union')
    caps=[r.vec() for _ in range(5)];assert all(len(b)%2==0 for b in caps)
    src=r.take(1);nb=na=b'\0'*8;parent=b''
    if src==b'\1':nb=r.take(8);na=r.take(8)
    elif src==b'\3':parent=r.vec()
    else:assert src==b'\2'
    ext=extensions(r);tbs=r.b[start:r.p];sig=r.vec()
    return [ek,sk,ctype,identity,certs,*caps,src,nb,na,parent,ext,sig,r.b[start:r.p],tbs]


def package(r):
    v=r.take(2);s=r.take(2);init=r.vec();lf=leaf(r);ext=extensions(r);tbs=r.b[:r.p];sig=r.vec()
    return [v,s,init,*lf,ext,sig,r.b[:r.p],tbs]


def group(r):
    v=r.take(2);s=r.take(2);gid=r.vec();epoch=r.take(8);tree=r.vec();confirmed=r.vec();ext=extensions(r)
    return [v,s,gid,epoch,tree,confirmed,ext,r.b[:r.p]]


def text(b):
    h=b.hex()
    return '\n'.join('"'+h[i:i+1024]+'"' for i in range(0,len(h),1024)) or '""'


def normal(fields): return b''.join(len(v).to_bytes(4,'big')+v for v in fields)


def point(key):return key.public_key().public_bytes(serialization.Encoding.X962,serialization.PublicFormat.UncompressedPoint)


def main():
    p=argparse.ArgumentParser();p.add_argument('--messages',type=Path,required=True);a=p.parse_args()
    raw=a.messages.read_bytes();assert hashlib.sha256(raw).hexdigest()==SHA
    corpus=[];digest=hashlib.sha256();suites=set()
    for item in json.loads(raw):
        kp=bytes.fromhex(item['mls_key_package']);assert kp[:4]==b'\0\1\0\5';kp=kp[4:]
        r=Reader(kp);fields=package(r);assert r.p==len(kp);suites.add(int.from_bytes(fields[1],'big'));corpus.append((1,kp));digest.update(normal(fields))
        lf=bytes.fromhex(item['update_proposal']);r=Reader(lf);fields=leaf(r);assert r.p==len(lf);corpus.append((2,lf));digest.update(normal(fields))
        gi=bytes.fromhex(item['mls_group_info']);assert gi[:4]==b'\0\1\0\4';r=Reader(gi[4:]);fields=group(r);gc=r.b[:r.p];corpus.append((3,gc));digest.update(normal(fields))
    # Exercise legal framing beyond the reference's fixed object caps and
    # alternate credential/source arms; no claim of semantic X509 validity.
    for source in [1,2,3]:
        credential=b'\0\2'+vector(vector(b'\x30\0')+vector(b'\x30\x01\0'))
        caps=b''.join(vector(b'\0\1') for _ in range(5))
        arm=b'\0'*8+b'\xff'*8 if source==1 else vector(b'x'*32) if source==3 else b''
        lf=vector(b'e'*65)+vector(b's'*65)+credential+caps+bytes([source])+arm+vector(b'\x0a\x0a'+vector(b'z'*5000))+vector(b'sig')
        r=Reader(lf);fields=leaf(r);assert r.p==len(lf);corpus.append((2,lf));digest.update(normal(fields))
    lines=['// MLSWG cfd450286d1bfd9cd2519b95c80f9771f94a5b1a and independent union/large-extension cases.',
        '// Generated by tools/mls_objects_oracle.py. Structural vectors need not be cryptographically valid.',
        'struct MlsObjectVector { u8 kind; const char* hex; };','constexpr MlsObjectVector mls_object_vectors[]{']
    for kind,b in corpus:lines.append('    {'+str(kind)+', '+text(b)+'},')
    lines += ['};',f'constexpr char mls_object_digest[] = "{digest.hexdigest()}";']
    signing=ec.derive_private_key(123,ec.SECP256R1());ek=point(ec.derive_private_key(456,ec.SECP256R1()));ik=point(ec.derive_private_key(789,ec.SECP256R1()))
    signed=[]
    for grease in [False,True]:
        ext=b'\x0a\x0a'+vector(b'unknown extension') if grease else b''
        credential=b'\0\1'+vector((0x0102030405060708).to_bytes(8,'big'))
        caps=vector(b'\0\1')+vector(b'\0\2')+vector(b'\x0a\x0a' if grease else b'')+vector(b'')+vector(b'\0\1')
        tbs=vector(ek)+vector(point(signing))+credential+caps+b'\1'+b'\0'*8+b'\xff'*8+vector(ext)
        ls=signing.sign(framed(b'LeafNodeTBS',tbs),ec.ECDSA(hashes.SHA256()))
        lf=tbs+vector(ls);ktbs=b'\0\1\0\2'+vector(ik)+lf+vector(ext)
        ks=signing.sign(framed(b'KeyPackageTBS',ktbs),ec.ECDSA(hashes.SHA256()))
        kp=ktbs+vector(ks);ref=hashlib.sha256(vector(b'MLS 1.0 KeyPackage Reference')+vector(kp)).digest()
        signed.append((kp,ref))
    lines += ['struct MlsSignedVector { const char* package; const char* reference; };','constexpr MlsSignedVector mls_signed_vectors[]{']
    for kp,ref in signed:lines.append('    {'+text(kp)+', '+text(ref)+'},')
    lines.append('};')
    Path('tests/data/mls_object_vectors.hpp').write_text('\n'.join(lines)+'\n',encoding='utf8')
    print(f'published_objects=900 independent_objects=3 suites={sorted(suites)} normalized_sha256={digest.hexdigest()} signed_packages=2')


if __name__=='__main__':main()
