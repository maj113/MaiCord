"""Independent RFC 9420 exporter and DAVE sender-key/frame vectors."""
from pathlib import Path
import hashlib
import sys
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
sys.dont_write_bytecode = True
from dave_key_derivation_oracle import label_expand


def export(secret, label, context, size):
    derived = label_expand(secret, label, b'', 32)
    return label_expand(derived, b'exported', hashlib.sha256(context).digest(), size)


def main():
    lines = ['// Generated by tools/mls_exporter_oracle.py; synthetic state only.']
    secret = bytes(range(32))
    digest = hashlib.sha256()
    count = 0
    for label_size in (0, 1, 23, 24, 55, 56, 100):
        label = bytes((97 + i % 26) for i in range(label_size))
        for context_size in (0, 1, 8, 55, 56, 63, 64, 65, 1025):
            context = bytes((i * 13 + 5) & 255 for i in range(context_size))
            for size in (0, 1, 16, 31, 32, 33, 65, 8160):
                digest.update(export(secret, label, context, size))
                count += 1
    lines.append(f'constexpr char exporter_matrix_digest[] = "{digest.hexdigest()}";')
    print(f'exporter_cases={count} sha256={digest.hexdigest()}')
    lines += ['struct ShaVector { u32 bytes; const char* digest; };', 'constexpr ShaVector sha_vectors[]{']
    for size in (0, 1, 55, 56, 63, 64, 65, 127, 128, 129, 1025):
        hashed = hashlib.sha256(bytes((i * 13 + 5) & 255 for i in range(size))).hexdigest()
        lines.append(f'    {{{size}, "{hashed}"}},')
    lines += ['};', 'struct ExportVector { u64 user; u32 epoch; const char* seed; const char* first; const char* second; };',
              'constexpr ExportVector export_vectors[]{']
    digest = hashlib.sha256()
    for user in (1, 255, 256, 65536, 0x0102030405060708, 0xffffffffffffffff):
        for epoch in (0, 1):
            secret = bytes((i + epoch * 19) & 255 for i in range(32))
            base = export(secret, b'Discord Secure Frames v0', user.to_bytes(8, 'little'), 16)
            key = label_expand(base, b'key', bytes(4), 16)
            body = bytes((i * 7 + epoch * 9) & 255 for i in range(32))
            frames = []
            for counter in (1, 2):
                encrypted = AESGCM(key).encrypt(bytes(8) + counter.to_bytes(4, 'little'), body, b'')
                frame = encrypted[:-16] + encrypted[-16:-8] + bytes([counter, 12, 250, 250])
                frames.append(frame.hex())
                digest.update(frame)
            lines.append(f'    {{{user}ull, {epoch}, "{base.hex()}", "{frames[0]}", "{frames[1]}"}},')
    lines.append('};\n')
    (Path(__file__).resolve().parents[1] / 'tests/data/mls_export_vectors.hpp').write_text('\n'.join(lines))
    print('sender_frames=24 sha256=' + digest.hexdigest())


if __name__ == '__main__':
    main()
