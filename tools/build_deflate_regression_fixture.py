"""Generate independent zlib fixtures for native match-copy regressions."""
from pathlib import Path
import zlib

from font_reference.embed_fixture import array_block, write_files


def inline(declaration, data):
    rows = ''.join('    '+','.join(f'0x{x:02x}' for x in data[j:j+24])+',\n' for j in range(0,len(data),24))
    return f'{declaration} = {{\n{rows}}};\n'


cases = []
for pattern in range(4):
    for size in [0, 1, 2, 3, 7, 31, 257, 258, 259, 4096, 65536]:
        data = bytes(65 if pattern == 0 else 65+i%3 if pattern == 1 else
                     ((i%257)*17)&255 if pattern == 2 else ((i%1021)*31+((i%1021)>>3))&255
                     for i in range(size))
        for strategy in [zlib.Z_DEFAULT_STRATEGY, zlib.Z_FIXED]:
            encoder = zlib.compressobj(6, zlib.DEFLATED, 15, 8, strategy)
            cases.append((pattern,size,encoder.compress(data)+encoder.flush()))
    data = bytes(((i%1021)*31+((i%1021)>>3))&255 for i in range(4096))
    cases.append((3,4096,zlib.compress(data,0)))
out = ['// Generated by tools/build_deflate_regression_fixture.py using Python zlib.',
       '#pragma once', '#include "maicord/core/slice.hpp"', 'namespace maicord {']
block, files = array_block(Path('tests/fixtures/deflate_matches'),
                           [(f'inline constexpr u8 kDeflateMatch{i}[]', f'kDeflateMatch{i}', data)
                            for i, (_, _, data) in enumerate(cases)], inline)
out.append(block.rstrip('\n'))
out.append('struct DeflateMatchFixture { const u8* data; u32 bytes; u32 size; u32 pattern; };')
out.append('inline constexpr DeflateMatchFixture kDeflateMatchFixtures[] = {')
for i,(pattern,size,data) in enumerate(cases):
    out.append(f'    {{kDeflateMatch{i}, sizeof(kDeflateMatch{i}), {size}, {pattern}}},')
out += ['};', '} // namespace maicord']
write_files(files)
Path('tests/fixtures/deflate_matches.hpp').write_text('\n'.join(out)+'\n',encoding='utf8')
print(len(cases),'fixtures')
