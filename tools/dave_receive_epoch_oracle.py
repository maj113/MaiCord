"""Independent encrypted sender-epoch frames. Synthetic secrets only."""
from pathlib import Path
import hashlib
import sys
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

sys.dont_write_bytecode = True
from dave_key_derivation_oracle import label_expand


def uleb(value):
    output = bytearray()
    while value >= 128:
        output.append((value & 127) | 128)
        value >>= 7
    output.append(value)
    return bytes(output)


def main():
    requests = {0: (1, 2, 0xfffffd, 0xfffffe, 0xffffff),
                1: (1, 2), 2: (1,), 5: (1,), 250: (1,), 251: (1,),
                255: (1,), 256: (1,), 257: (1,), 0xffffffff: (1, 2)}
    secret = bytes(range(16))
    keys = {}
    for generation in range(258):
        context = generation.to_bytes(4, 'big')
        keys[generation] = label_expand(secret, b'key', context, 16)
        secret = label_expand(secret, b'secret', context, 32)
    # Terminal generation boundary test installs a synthetic ratchet checkpoint.
    keys[0xffffffff] = label_expand(bytes(range(16)), b'key', bytes([255]) * 4, 16)
    lines = ['// Generated by tools/dave_receive_epoch_oracle.py; synthetic keys only.',
             'struct EpochVector { u32 generation, counter; const char* wire; };',
             'constexpr EpochVector epoch_vectors[]{']
    digest = hashlib.sha256()
    for generation, counters in requests.items():
        for counter in counters:
            truncated = ((generation & 255) << 24) | counter
            nonce = bytes(8) + truncated.to_bytes(4, 'little')
            body = bytes((i * 17 + 9) & 255 for i in range(32))
            encrypted = AESGCM(keys[generation]).encrypt(nonce, body, b'')
            metadata = uleb(truncated)
            wire = encrypted[:-16] + encrypted[-16:-8] + metadata + bytes([len(metadata) + 11, 250, 250])
            digest.update(wire)
            lines.append(f'    {{{generation}u, {counter}u, "{wire.hex()}"}},')
    lines.append('};\n')
    (Path(__file__).resolve().parents[1] / 'tests/data/dave_epoch_vectors.hpp').write_text('\n'.join(lines))
    print('frames=' + str(sum(map(len, requests.values()))) + ' sha256=' + digest.hexdigest())


if __name__ == '__main__':
    main()
