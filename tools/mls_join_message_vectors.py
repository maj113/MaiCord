"""Independent MLS Welcome/GroupInfo fields from pinned MLSWG messages corpus."""
import argparse
import hashlib
import json
from pathlib import Path
from mls_objects_oracle import Reader, SHA, extensions, group, normal, text, vector


def welcome(r):
    suite = r.take(2)
    entries = r.vec()
    fields = [suite, entries]
    q = Reader(entries)
    while q.p < len(entries):
        start = q.p
        fields += [q.vec(), q.vec(), q.vec(), entries[start:q.p]]
    fields += [r.vec(), r.b[:r.p]]
    return fields


def group_info(r):
    fields = group(r)
    fields += [extensions(r), r.vec(), r.take(4)]
    tbs = r.b[:r.p]
    fields += [r.vec(), r.b[:r.p], tbs]
    return fields


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--messages", type=Path, required=True)
    args = parser.parse_args()
    raw = args.messages.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == SHA
    corpus = []
    for record in json.loads(raw):
        corpus.extend(bytes.fromhex(record[key]) for key in ["mls_welcome", "mls_group_info"])
    corpus.append(b"\0\1\0\3\0\2\0\0") # Empty list: structurally valid, not authenticated.
    corpus.append(b"\0\1\0\3\0\2" + vector(b"\0\0\0" * 1024) + vector(b"encrypted"))
    corpus.append(b"\0\1\0\3\0\2" + vector(vector(b"ref") + vector(b"kem") + vector(b"cipher")) + vector(b"x" * 16384))
    context = b"\0\1\0\2" + vector(b"group") + b"\xff" * 8 + vector(b"tree") + vector(b"transcript") + vector(b"")
    info = context + vector(b"\x0a\x0a" + vector(b"x" * 5000)) + vector(b"tag") + b"\xff" * 4 + vector(b"sig")
    corpus.append(b"\0\1\0\4" + info)
    digest = hashlib.sha256()
    for wire in corpus:
        assert wire[:2] == b"\0\1"
        kind = int.from_bytes(wire[2:4], "big")
        r = Reader(wire[4:])
        fields = welcome(r) if kind == 3 else group_info(r)
        assert r.p == len(r.b)
        digest.update(normal([wire[:2], wire[2:4], *fields, wire]))
    lines = ["// Pinned MLSWG cfd450286d1bfd9cd2519b95c80f9771f94a5b1a, plus structural boundaries.",
             "// Generated by tools/mls_join_message_vectors.py. Not cryptographic validity fixtures.",
             "constexpr const char* mls_join_message_vectors[]{"]
    lines += [text(wire) + "," for wire in corpus]
    lines += ["};", f'constexpr char mls_join_message_digest[] = "{digest.hexdigest()}";']
    Path("tests/data/mls_join_message_vectors.hpp").write_text("\n".join(lines) + "\n", encoding="utf8")
    print(f"published_messages=600 independent_messages=4 normalized_sha256={digest.hexdigest()} max_bytes={max(map(len, corpus))}")


if __name__ == "__main__":
    main()
