"""RFC 9420 appendix C array-tree arithmetic vectors (stdlib only)."""
from pathlib import Path
import hashlib


def log2(x):
    k = 0
    while (x >> k) > 0:
        k += 1
    return k - 1


def level(x):
    if x & 1 == 0:
        return 0
    k = 0
    while (x >> k) & 1 == 1:
        k += 1
    return k


def node_width(n):
    return 0 if n == 0 else 2 * (n - 1) + 1


def root(n):
    return (1 << log2(node_width(n))) - 1


def left(x):
    k = level(x)
    return None if k == 0 else x ^ (0x01 << (k - 1))


def right(x):
    k = level(x)
    return None if k == 0 else x ^ (0x03 << (k - 1))


def parent(x, n):
    if x == root(n):
        return None
    k = level(x)
    b = (x >> (k + 1)) & 0x01
    return (x | (1 << k)) ^ (b << (k + 1))


def sibling(x, n):
    p = parent(x, n)
    if p is None:
        return None
    return right(p) if x < p else left(p)


def direct_path(x, n):
    r, d = root(n), []
    if x == r:
        return d
    while x != r:
        x = parent(x, n)
        d.append(x)
    return d


def copath(x, n):
    if x == root(n):
        return []
    d = direct_path(x, n)
    d.insert(0, x)
    d.pop()
    return [sibling(y, n) for y in d]


def common_ancestor(x, y):
    # Lowest common ancestor of two leaves by shifting off differing bits.
    lx, ly = level(x) + 1, level(y) + 1
    if lx <= ly and x >> ly == y >> ly:
        return y
    if ly <= lx and x >> lx == y >> lx:
        return x
    xn, yn, k = x, y, 0
    while xn != yn:
        xn, yn, k = xn >> 1, yn >> 1, k + 1
    return (xn << k) + (1 << (k - 1)) - 1


def encode(value):
    return 0xffffffff if value is None else value


def main():
    rows, digest = [], hashlib.sha256()
    for n in list(range(1, 18)) + [32, 33]:
        width = node_width(n)
        for x in range(width):
            fields = [n, x, root(n), encode(left(x)), encode(right(x)), encode(parent(x, n)), encode(sibling(x, n))]
            rows.append(fields)
            digest.update(bytes(str(fields), 'ascii'))
    paths = []
    for n in [1, 2, 3, 5, 8, 11, 32]:
        for leaf in range(n):
            x = 2 * leaf
            d, c = direct_path(x, n), copath(x, n)
            paths.append((n, x, d, c))
            digest.update(bytes(str((n, x, d, c)), 'ascii'))
    ancestors = []
    for a in range(9):
        for b in range(9):
            if a != b:
                ancestors.append((a, b, common_ancestor(2 * a, 2 * b)))
    lines = ['// Generated by tools/mls_tree_math_oracle.py (RFC 9420 appendix C).',
             '// 0xffffffff marks an undefined relation.',
             'struct TreeMathVector { u32 leaves, node, root, left, right, parent, sibling; };',
             'constexpr TreeMathVector tree_math_vectors[]{']
    lines += ['    {' + ', '.join(f'{v}u' for v in row) + '},' for row in rows]
    lines += ['};', 'struct TreePathVector { u32 leaves, node, count; u32 direct[6], copath[6]; };',
              'constexpr TreePathVector tree_path_vectors[]{']
    for n, x, d, c in paths:
        pad = lambda v: ', '.join(f'{y}u' for y in v + [0] * (6 - len(v)))
        lines.append(f'    {{{n}u, {x}u, {len(d)}u, {{{pad(d)}}}, {{{pad(c)}}}}},')
    lines += ['};', 'struct TreeAncestorVector { u32 left_leaf, right_leaf, ancestor; };',
              'constexpr TreeAncestorVector tree_ancestor_vectors[]{']
    lines += [f'    {{{a}u, {b}u, {c}u}},' for a, b, c in ancestors]
    lines.append('};\n')
    out = Path(__file__).resolve().parents[1] / 'tests/data/mls_tree_math_vectors.hpp'
    out.write_text('\n'.join(lines), encoding='utf8', newline='\n')
    print(f'relations={len(rows)} paths={len(paths)} ancestors={len(ancestors)} sha256={digest.hexdigest()}')


if __name__ == '__main__':
    main()
