"""Independent MLS framing/DER oracle and native DER signature verification."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, utils

SOURCE_SHA = '17cfcf89af9f51d0f2aa7af77f6f9ec99376a039214b6d42a6f11646b83e8c29'
LABEL_LENGTHS = [0, 1, 55, 56, 63, 64, 65, 16375, 16376, 16383, 16384]
CONTENT_LENGTHS = [0, 1, 55, 56, 63, 64, 65, 16383, 16384]


def vector(data):
    n = len(data)
    header = bytes([n]) if n < 64 else (n | (0x4000 if n < 16384 else 0x80000000)).to_bytes(2 if n < 16384 else 4, 'big')
    return header + data


def framed(label, content, sign=True):
    return vector((b'MLS 1.0 ' if sign else b'') + label) + vector(content)


def pattern(n, factor, add):
    return bytes((i * factor + add) & 255 for i in range(n))


def verify_native(path):
    data = path.read_bytes()
    cursor = count = 0
    while cursor != len(data):
        point = data[cursor:cursor+65]
        cursor += 65
        nl, nc, ns = struct.unpack_from('<III', data, cursor)
        cursor += 12
        assert ns <= 72 and cursor + nl + nc + ns <= len(data)
        label = data[cursor:cursor+nl]
        cursor += nl
        content = data[cursor:cursor+nc]
        cursor += nc
        sig = data[cursor:cursor+ns]
        cursor += ns
        ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), point).verify(
            sig, framed(label, content), ec.ECDSA(hashes.SHA256()))
        count += 1
    assert count >= 1
    print(f'OpenSSL verified {count} native MLS DER signatures from independently framed messages')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--vectors', type=Path)
    parser.add_argument('--verify-native', type=Path)
    args = parser.parse_args()
    if args.verify_native:
        verify_native(args.verify_native)
        return
    source = args.vectors.read_bytes()
    assert hashlib.sha256(source).hexdigest() == SOURCE_SHA
    v = next(item for item in json.loads(source) if item['cipher_suite'] == 2)
    s = v['sign_with_label']
    point, scalar, content, sig = [bytes.fromhex(s[k]) for k in ['pub', 'priv', 'content', 'signature']]
    label = s['label'].encode()
    pub = ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), point)
    pub.verify(sig, framed(label, content), ec.ECDSA(hashes.SHA256()))
    key = ec.derive_private_key(int.from_bytes(scalar, 'big'), ec.SECP256R1())
    assert key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint) == point
    ref = v['ref_hash']
    assert hashlib.sha256(framed(ref['label'].encode(), bytes.fromhex(ref['value']), False)).hexdigest() == ref['out']
    cases = [(label, content, sig)]
    for i, label in enumerate([b'', b'FramedContentTBS', b'LeafNodeTBS', b'KeyPackageTBS', b'GroupInfoTBS',
                               b'Extension\x00UTF8\xc5\xbe', pattern(56, 7, 9), pattern(65, 7, 9), pattern(16376, 7, 9)]):
        content = pattern(CONTENT_LENGTHS[i], 13, 5)
        cases.append((label, content, key.sign(framed(label, content), ec.ECDSA(hashes.SHA256()))))
    lines = ['// MLSWG cfd450286d1bfd9cd2519b95c80f9771f94a5b1a and independent OpenSSL answers.',
             '// Generated by tools/mls_signature_oracle.py; synthetic/public test keys only.',
             f'constexpr char signature_scalar[] = "{scalar.hex()}";', f'constexpr char signature_point[] = "{point.hex()}";',
             'struct MlsSignVector { const char *label, *content, *signature; };', 'constexpr MlsSignVector mls_sign_vectors[]{']
    for l, c, sig in cases:
        lines.append('    {' + ', '.join('"' + field.hex() + '"' for field in [l, c, sig]) + '},')
    lines += ['};', f'constexpr char ref_label[] = "{ref["label"].encode().hex()}";',
              f'constexpr char ref_value[] = "{ref["value"]}";', f'constexpr char ref_expected[] = "{ref["out"]}";']
    # Keep large generated literals MSVC-compatible without a huge single token.
    import re
    lines = [re.sub(r'"([0-9a-f]{1025,})"', lambda m: '\n'.join('"' + m[1][i:i+1024] + '"' for i in range(0, len(m[1]), 1024)), line) for line in lines]
    aggregate = hashlib.sha256()
    for sign in [False, True]:
        for nl in LABEL_LENGTHS:
            for nc in CONTENT_LENGTHS:
                aggregate.update(hashlib.sha256(framed(pattern(nl, 7, 9), pattern(nc, 13, 5), sign)).digest())
    lines += ['constexpr u32 signature_label_lengths[]{' + ','.join(map(str, LABEL_LENGTHS)) + '};',
              'constexpr u32 signature_content_lengths[]{' + ','.join(map(str, CONTENT_LENGTHS)) + '};',
              f'constexpr char signature_hash_matrix[] = "{aggregate.hexdigest()}";']
    der_digest = hashlib.sha256()
    for pos in range(32):
        for j, val in enumerate([1, 127, 128, 255]):
            r = val << (8 * (31-pos))
            s = ((val ^ 0x55) | 1) << (8 * (31-((pos*7+j) % 32)))
            der_digest.update(utils.encode_dss_signature(r, s))
    lines.append(f'constexpr char signature_der_matrix[] = "{der_digest.hexdigest()}";')
    Path('tests/data/mls_signature_vectors.hpp').write_text('\n'.join(lines) + '\n', encoding='utf8')
    print(f'published_source_sha256={SOURCE_SHA} signatures={len(cases)} hash_cases={2*len(LABEL_LENGTHS)*len(CONTENT_LENGTHS)} hash_sha256={aggregate.hexdigest()}')


if __name__ == '__main__':
    main()
