"""First-party Gurmukhi original-cluster inputs; no font payload."""
CONSONANTS=(*range(0xa15,0xa29),*range(0xa2a,0xa31),0xa32,0xa33,0xa35,0xa36,0xa38,0xa39,0xa59,0xa5a,0xa5b,0xa5c,0xa5e)
SIGNS=(0xa3c,0xa3e,0xa3f,0xa40,0xa41,0xa42,0xa47,0xa48,0xa4b,0xa4c,0xa4d,0xa01,0xa02,0xa03,0xa51,0xa70,0xa71,0xa75)

def corpus():
    cases={}
    def add(s,g):cases.setdefault(tuple(s),g)
    for c in CONSONANTS:
        add((c,),'nominal')
        for sign in SIGNS:add((c,sign),'signs')
        for other in CONSONANTS:
            add((c,0xa4d,other),'conjuncts')
            add((c,0xa4d,other,0xa3f),'conjunct-pre-vowel')
        for control in (0x200c,0x200d):add((c,0xa4d,control),'controls')
    for sign in SIGNS:add((sign,),'orphans')
    for scalar in (0xa05,0xa06,0xa07,0xa08,0xa09,0xa0a,0xa0f,0xa10,0xa13,0xa14,0xa72,0xa73):add((scalar,),'independent')
    return list(cases.items())

def complex_corpus():
    import itertools
    cases={}
    def add(s,g):cases.setdefault(tuple(s),g)
    bases=(0xa15,0xa1c,0xa24,0xa26,0xa2f,0xa30,0xa35,0xa39)
    signs=(0xa3f,0xa41,0xa47,0xa4b,0xa4c,0xa3e,0xa40,0xa48)
    for i,(a,b,c) in enumerate(itertools.product(bases,repeat=3)):
        add((a,0xa4d,b,0xa4d,c,signs[i%len(signs)]),'three-consonants')
    for base in bases:
        for sign in signs:
            for prefix in ((base,0xa3c),(base,0xa4d,0xa3c,0xa15),(0xa30,0xa4d,base),(base,0xa4d,0x200d,0xa15),(base,0xa51),(base,0xa75)):
                add((*prefix,sign,0xa70),'marks-and-controls')
            for extra in (0xa3e,0xa40):add((base,sign,extra),'multiple-matras')
    return list(cases.items())
