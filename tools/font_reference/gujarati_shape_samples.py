def corpus():
    consonants=(*range(0xa95,0xaa9),*range(0xaaa,0xab1),0xab2,0xab3,0xab5,*range(0xab6,0xaba),0xaf9)
    signs=(0xabc,0xabe,0xabf,0xac0,0xac1,0xac2,0xac3,0xac4,0xac5,0xac7,0xac8,0xac9,0xacb,0xacc,0xacd,0xae2,0xae3,0xa81,0xa82,0xa83,0xafb,0xafc,0xafd,0xafe,0xaff)
    cases={}
    def add(s,group):cases.setdefault(tuple(s),group)
    for c in consonants:
        add((c,),'nominal')
        for sign in signs:add((c,sign),'signs')
        for other in consonants:
            add((c,0xacd,other),'conjuncts')
            add((c,0xacd,other,0xabf),'conjunct-pre-vowel')
        for control in (0x200c,0x200d):add((c,0xacd,control),'controls')
    for sign in signs:add((sign,),'orphans')
    for scalar in (0xa85,0xa86,0xa87,0xa88,0xa89,0xa8a,0xa8b,0xa8c,0xa8d,0xa8f,0xa90,0xa91,0xa93,0xa94,0xae0,0xae1):add((scalar,),'independent')
    return list(cases.items())

def complex_corpus():
    import itertools
    cases={}
    def add(s,group):cases.setdefault(tuple(s),group)
    bases=(0xa95,0xa9c,0xaa4,0xaa6,0xaac,0xaaf,0xab0,0xab3)
    signs=(0xabf,0xac1,0xac7,0xacb,0xacc,0xabe,0xac0,0xac8,0xac9)
    for i,(a,b,c) in enumerate(itertools.product(bases,repeat=3)):
        add((a,0xacd,b,0xacd,c,signs[i%len(signs)]),'three-consonants')
    for base in bases:
        for sign in signs:
            for prefix in ((base,0xabc),(base,0xacd,0xabc,0xa95),(0xab0,0xacd,base),(base,0xacd,0x200d,0xa95)):
                add((*prefix,sign,0xa81),'nukta-reph-controls')
            for extra in (0xabe,0xac0,0xac9):add((base,sign,extra),'multiple-matras')
    for s in ((0xa0,0xacb),(0x200d,0xacb),(0x200d,),
              (0xab0,0x200c,0xacd,0xa95,0xabf),(0xa95,0xa0,0xabf),
              (0xab0,0xacd,0xa95,0xa0,0xabf),(0xab0,0xacd,0xa95,0xac9)):
        add(s,'specials')
    return list(cases.items())
