"""First-party Bengali original-cluster corpus; no installed font data."""
def corpus():
    consonants=(*range(0x995,0x9a9),*range(0x9aa,0x9b1),0x9b2,*range(0x9b6,0x9ba),0x9dc,0x9dd,0x9df,0x9f0,0x9f1)
    signs=(0x9bc,0x9be,0x9bf,0x9c0,0x9c1,0x9c2,0x9c3,0x9c4,0x9c7,0x9c8,0x9cb,0x9cc,0x9cd,0x9d7,0x9e2,0x9e3,0x981,0x982,0x983)
    cases={}
    def add(s,group):
        cases.setdefault(tuple(s),group)
    for c in consonants:
        add((c,),'nominal')
        for sign in signs:
            add((c,sign),'signs')
        for tail in ((0x9c7,0x9be),(0x9c7,0x9d7)):
            add((c,*tail),'decomposed-vowels')
        for other in consonants:
            add((c,0x9cd,other),'conjuncts')
            add((c,0x9cd,other,0x9cb),'conjunct-split-vowels')
        for control in (0x200c,0x200d):
            add((c,0x9cd,control),'controls')
    for sign in signs:
        add((sign,),'orphans')
    for scalar in (0x985,0x986,0x987,0x988,0x989,0x98a,0x98b,0x98c,0x98f,0x990,0x993,0x994,0x9ce):
        add((scalar,),'independent')
    return list(cases.items())

def complex_corpus():
    import itertools
    cases={}
    def add(s,group):
        cases.setdefault(tuple(s),group)
    bases=(0x995,0x99c,0x9a4,0x9a6,0x9ac,0x9af,0x9b0,0x9f0)
    signs=(0x9bf,0x9c1,0x9c7,0x9cb,0x9cc,0x9be,0x9c0,0x9c8)
    for i,(a,b,c) in enumerate(itertools.product(bases,repeat=3)):
        add((a,0x9cd,b,0x9cd,c,signs[i%len(signs)]),'three-consonants')
    for base in bases:
        for sign in signs:
            for prefix in ((base,0x9bc),(base,0x9cd,0x9bc,0x995),(0x9b0,0x9cd,base),(base,0x9cd,0x200d,0x995)):
                add((*prefix,sign,0x981),'nukta-reph-controls')
            for extra in (0x9be,0x9c0,0x9d7):
                add((base,sign,extra),'multiple-matras')
    for s in ((0x985,0x9cb),(0x985,0x9cc),(0x995,0x9bf,0x9cb),(0x995,0x9c7,0x9cc),
              (0xa0,0x9cb),(0x200d,0x9cb),(0x200d,),(0x9b0,0x200c,0x9cd,0x995,0x9cb)):
        add(s,'specials')
    return list(cases.items())
