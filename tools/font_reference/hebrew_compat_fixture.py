"""Embed first-party font probes for native-only Hebrew regression tests."""
from pathlib import Path
import argparse,hashlib,json
from embed_fixture import write_embedded_arrays

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('oracles',type=Path,nargs='+');p.add_argument('--output',required=True,type=Path);a=p.parse_args()
    fonts=[];rows=[];lines=['// Generated by hebrew_compat_fixture.py. First-party QA fonts only.']
    for path in a.oracles:
        data=json.loads(path.read_text());font=Path(data['font']['path']);raw=font.read_bytes()
        assert hashlib.sha256(raw).hexdigest()==data['font']['sha256']
        # These fonts are generated by the accompanying first-party probes.
        assert font.parent.name.startswith('native-hebrew-') and font.parent.parent.name=='qa'
        if font not in fonts:fonts.append(font)
        rows.extend((fonts.index(font),r) for r in data['rows'])
        lines.append('// Oracle SHA-256: '+hashlib.sha256(path.read_bytes()).hexdigest())
    def array(kind,name,values):
        lines.append(f'constexpr {kind} {name}[]{{')
        lines.extend('    '+','.join(str(v) for v in values[i:i+24])+',' for i in range(0,len(values),24));lines.append('};')
    lines.append(write_embedded_arrays(a.output.with_suffix(''),[(f'constexpr u8 hebrew_compat_font_{i}[]',f'hebrew_compat_font_{i}',font.read_bytes()) for i,font in enumerate(fonts)]).rstrip('\n'))
    lines.append('constexpr ConstSlice<u8> hebrew_compat_fonts[]{')
    lines.extend(f'    {{hebrew_compat_font_{i},sizeof(hebrew_compat_font_{i})}},' for i in range(len(fonts)));lines.append('};')
    for i,(_,r) in enumerate(rows):
        array('u16',f'hebrew_glyphs_{i}',r['glyphs']);array('u32',f'hebrew_clusters_{i}',r['clusters']);array('u32',f'hebrew_placements_{i}',sum(r['placement_bits'],[]))
    lines+=['struct HebrewCompatibilityCase {u32 font,mode;Utf8View text;ConstSlice<u16> glyphs;ConstSlice<u32> clusters,placements;};','constexpr HebrewCompatibilityCase hebrew_compat_cases[]{']
    for i,(font,r) in enumerate(rows):
        encoded=''.join(map(chr,r['text'])).encode();literal=''.join(f'\\x{v:02x}' for v in encoded);mode=(r['mode']&1)|((r['mode']&2)<<1)
        lines.append(f'    {{{font},{mode},{{"{literal}",{len(encoded)}}},{{hebrew_glyphs_{i},{len(r["glyphs"])}}},{{hebrew_clusters_{i},{len(r["clusters"])}}},{{hebrew_placements_{i},{len(r["placement_bits"])*3}}}}},')
    a.output.write_text('\n'.join(lines+['};','']),encoding='utf-8');print(len(fonts),'fonts;',len(rows),'Hebrew cases')
if __name__=='__main__':main()
