"""Bounded synthetic Windows Khmer feature-policy observations, offline QA.

FontTools authors fonts only. These probes observe eligibility and scheduling;
they do not establish native shaping, app admission or pixel correctness.
"""
import argparse,json,subprocess,sys,threading,time
from pathlib import Path
from fontTools.ttLib import TTFont,newTable
from feature_plan_oracle import language,script,layout
from gsub_execution_oracle import make_font,lookup,single,marker,ORDER,identity
from gpos_execution_oracle import adjust

SUBSTITUTION=('locl','ccmp','pref','blwf','abvf','pstf','cfar','pres','blws','abvs','psts','clig','liga','calt','rclt','rlig','rvrn','nukt','akhn','rphf','half','init','isol','cjct','vatu')
POSITION=('curs','dist','kern','mark','abvm','blwm','mkmk')
CONTEXTS={'base':'1780','pre':'1780,17d2,179a','below':'1780,17d2,1780','post':'1780,17d2,1799',
          'after-ro':'1780,17d2,179a,17d2,1799','above-split':'1780,17be','post-split':'1780,17c4','shift':'1780,17c9,17be'}
CMAP={0x1780:'A',0x17d2:'B',0x179a:'C',0x1799:'D',0x17bb:'E',0x17be:'X',0x17c4:'Y',0x17c1:'Z',0x17c9:'M',0x17cc:'N',0x25cc:'L'}

def scenarios():
    yield dict(name='control',kind='GSUB',features=[('test',[0])],lookups=[marker()])
    for kind,tags in [('GSUB',SUBSTITUTION),('GPOS',POSITION)]:
        for tag in tags:
            yield dict(name=kind+'-'+tag,kind=kind,features=[(tag,[0])],lookups=[marker() if kind=='GSUB' else adjust('A',0,0,31)])


    pairs=(('locl','ccmp'),('ccmp','pref'),('pref','blwf'),('blwf','abvf'),('abvf','pstf'),('pstf','cfar'),
           ('cfar','pres'),('pres','blws'),('blws','abvs'),('abvs','psts'),('psts','clig'),('clig','rclt'))
    for tags in pairs:
        for reverse in (False,True):
            yield dict(name='order-'+'-'.join(tags)+'-'+str(int(reverse)),kind='GSUB',
                features=sorted([(tags[0],[int(reverse)]),(tags[1],[int(not reverse)])]),
                lookups=[lookup(1,single({'A':'B'})),lookup(1,single({'B':'C'}))])
        yield dict(name='shared-'+'-'.join(tags),kind='GSUB',features=sorted((tag,[0]) for tag in tags),
            lookups=[lookup(1,single(dict(zip(ORDER[1:-1],ORDER[2:]))))])
    for tag in ['test','ccmp','clig']:
        yield dict(name='required-'+tag,kind='GSUB',features=[(tag,[0])],required=0,
            lookups=[lookup(1,single(dict(zip(ORDER[1:-1],ORDER[2:]))))])
    for tags in [('dist','blwm'),('blwm','abvm'),('abvm','mkmk')]:
        yield dict(name='shared-pos-'+'-'.join(tags),kind='GPOS',features=sorted((tag,[0]) for tag in tags),lookups=[adjust('A',0,0,31)])
    yield dict(name='required-pos-test',kind='GPOS',features=[('test',[0])],required=0,lookups=[adjust('A',0,0,31)])

    for name,langs in [('eng-default',script(language([0]),{'ENG ':language([1])})),
                       ('eng-only',script(None,{'ENG ':language([1])})),
                       ('khm-default',script(language([0]),{'KHM ':language([1])})),
                       ('khm-only',script(None,{'KHM ':language([1])}))]:
        yield dict(name='language-'+name,kind='GSUB',features=[('ccmp',[0]),('locl',[1])],
            lookups=[lookup(1,single({'A':'B'})),lookup(1,single({'A':'C'}))],scripts={'khmr':langs})

def write_unit_fixture(destination,folder):
    """First-party schedule fixture; no installed font data is embedded."""
    features=[('abvs',[1]),('ccmp',[0,4]),('cfar',[2,3]),('clig',[3]),
              ('locl',[4]),('pref',[5]),('pres',[0]),('test',[6])]
    lines=['// Generated by khmer_plan_policy.write_unit_fixture; first-party data.']
    folder.mkdir(parents=True,exist_ok=True)
    for required in (False,True):
        path=folder/('required.ttf' if required else 'normal.ttf')
        make_font(path,dict(name='khmer-unit',lookups=[lookup(1,single({'A':'B'}))]*8))
        with TTFont(path,recalcTimestamp=False) as font:
            font['GSUB'].table=layout('GSUB',features,[lookup(1,single({'A':'B'}))]*8,
                {'khmr':script(language(list(range(8)),7 if required else 65535))})
            data=font['GSUB'].compile(font);font.save(path)
        lines.append('constexpr u8 khmer_'+('required' if required else 'plan')+'_fixture[]{')
        lines.extend('    '+','.join(str(v) for v in data[at:at+32])+',' for at in range(0,len(data),32))
        lines.append('};')
    destination.write_text('\n'.join(lines)+'\n',encoding='utf-8')

def worker(args):
    start=time.perf_counter();result=dict(status='running',reference=identity(args.reference),source=identity(Path(__file__)),scope=__doc__,checks=[])
    destination=args.output_dir/'result.json'
    for case in scenarios():
        if args.case and case['name'] not in args.case:continue
        path=args.output_dir/(case['name']+'.ttf')
        make_font(path,dict(name=case['name'],lookups=[lookup(1,single({'A':'A'}))]))
        with TTFont(path,recalcTimestamp=False) as font:
            for cmap in font['cmap'].tables:
                if cmap.isUnicode():cmap.cmap.update(CMAP)
            del font['GSUB']
            other='GPOS' if case['kind']=='GSUB' else 'GSUB'
            font[other]=newTable(other)
            font[other].table=layout(other,[('dist' if other=='GPOS' else 'ccmp',[0])],
                [adjust('A',0,0,0) if other=='GPOS' else lookup(1,single({'A':'A'}))],{'khmr':script(language([0]))})
            font[case['kind']]=newTable(case['kind'])
            font[case['kind']].table=layout(case['kind'],case['features'],case['lookups'],case.get('scripts',{'khmr':script(language(range(len(case['features'])),case.get('required',65535)))}))
            font.save(path)
        row=dict(name=case['name'],font=identity(path),observations=[]);result['checks'].append(row)
        for context,text in CONTEXTS.items():
            if args.context and context not in args.context:continue
            for mode in ('default','liga=0,clig=0,kern=0'):
                run=subprocess.run([str(args.reference),str(path),text,mode,'1148846080','0','0','en-US'],capture_output=True,text=True,timeout=2,creationflags=subprocess.CREATE_NO_WINDOW)
                if run.returncode:raise RuntimeError(run.stdout+run.stderr)
                value=json.loads(run.stdout)
                if value['hresult'] or value['placement_hresult']:raise RuntimeError(value)
                row['observations'].append(dict(context=context,text=text,mode=mode,glyph_names=[ORDER[g] for g in value['glyphs']],result=value))
        destination.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    result.update(status='observed',seconds=time.perf_counter()-start)
    destination.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8');print(sum(len(c['observations']) for c in result['checks']),'observations',round(result['seconds'],2),'seconds')
    return 0

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--reference',type=Path,required=True);parser.add_argument('--output-dir',type=Path,required=True)
    parser.add_argument('--case',action='append');parser.add_argument('--context',action='append',choices=tuple(CONTEXTS));parser.add_argument('--worker',action='store_true',help=argparse.SUPPRESS)
    args=parser.parse_args()
    if args.worker:return worker(args)
    args.output_dir.mkdir(parents=True,exist_ok=True);path=args.output_dir/'result.json';path.write_text('{"status":"running"}',encoding='utf-8')
    sys.path.insert(0,str(Path(__file__).resolve().parents[1]));from verify_native_text import run_check,CheckFailure
    try:execution=run_check('khmer-policy',[sys.executable,str(Path(__file__).resolve()),*sys.argv[1:],'--worker'],Path.cwd(),args.output_dir,5,threading.Event())
    except CheckFailure as error:execution=error.row
    result=json.loads(path.read_text(encoding='utf-8'));result['execution']=execution
    if execution['exit']:result['status']=execution['status']
    path.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8');return execution['exit']
if __name__=='__main__':raise SystemExit(main())
