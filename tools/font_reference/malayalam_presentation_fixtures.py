"""First-party Windows probes for Malayalam presentation scheduling (offline QA)."""
import argparse
import hashlib
import itertools
import json
from pathlib import Path
from fontTools.ttLib import TTFont, newTable
from gsub_execution_oracle import make_font, lookup, single, ligature
from feature_plan_oracle import layout, language, script


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir',type=Path,required=True)
    parser.add_argument('--scenario',action='append',help='Select named scenarios; default includes all.')
    parser.add_argument('--unit-output',type=Path,help='Emit the three scheduling fixtures for the native unit test.')
    args=parser.parse_args();out=args.output_dir;out.mkdir(parents=True,exist_ok=True)
    if (out/'manifest.json').exists():raise ValueError('Preserve completed font evidence')
    tags=['pres','abvs','blws','psts','haln','calt','rclt'];rows=[]
    scenarios=[]
    for a,b in itertools.combinations(tags,2):
        scenarios.append((a+'-'+b,[(a,[1]),(b,[0])],[lookup(1,single({'X':'Y'})),lookup(1,single({'A':'X'}))]))
    scenarios.append(('shared',[('pres',[0]),('blws',[0])],[lookup(1,single({'A':'X','X':'Y'}))]))
    scenarios.append(('shared-context',[('calt',[0]),('rclt',[0])],[lookup(1,single({'A':'X','X':'Y'}))]))
    scenarios.append(('within-feature',[('pres',[1,0])],[lookup(1,single({'X':'Y'})),lookup(1,single({'A':'X'}))]))
    scenarios.append(('within-repeat',[('pres',[0,0])],[lookup(1,single({'A':'X','X':'Y'}))]))
    for name,features,lookups in scenarios:
        if args.scenario and name not in args.scenario:continue
        for post in (False,True):
            label=name+('-post' if post else '-default');path=out/(label+'.ttf')
            if path.exists():raise ValueError('Existing font payload')
            make_font(path,dict(name='Malayalam-'+label,lookups=lookups))
            font=TTFont(path,recalcTimestamp=False)
            for cmap in font['cmap'].tables:
                if cmap.isUnicode():cmap.cmap.update({0x20:'tagN',0xd15:'A',0xd2f:'E',0xd4d:'tagX',0x25cc:'tagM'})
            current_features=list(features);current_lookups=list(lookups)
            if post:
                current_features.append(('pstf',[len(current_lookups)]));current_lookups.append(ligature(['tagX','E'],'tagE'))
            font['GSUB'].table=layout('GSUB',current_features,current_lookups,{'mlm2':script(language(list(range(len(current_features)))))})
            font['GPOS']=newTable('GPOS');font['GPOS'].table=layout('GPOS',[],[],{'mlm2':script(language([]))})
            font.save(path);rows.append(dict(name=label,path=str(path.resolve()),sha256=hashlib.sha256(path.read_bytes()).hexdigest(),post_form=post,features=current_features))
    if args.unit_output:
        units=['// First-party font GSUB payloads; generated by malayalam_presentation_fixtures.py.']
        for label,name in [('ordered','pres-blws-default'),('shared','shared-context-default'),('repeat','within-repeat-default')]:
            with TTFont(out/(name+'.ttf')) as font:data=font['GSUB'].compile(font)
            units.append('constexpr u8 malayalam_presentation_'+label+'[]{')
            units+=['    '+','.join(str(v) for v in data[at:at+24])+',' for at in range(0,len(data),24)]
            units.append('};')
        payload='\n'.join(units)+'\n'
        if args.unit_output.exists() and args.unit_output.read_text()!=payload:raise ValueError('Existing unit fixture differs')
        if not args.unit_output.exists():args.unit_output.write_text(payload)
    (out/'cases.json').write_text(json.dumps([[0xd15]]))
    (out/'manifest.json').write_text(json.dumps(rows,indent=2));print(len(rows),'first-party scheduling fonts')


if __name__=='__main__':main()
