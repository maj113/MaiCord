"""Embed captured first-party Windows probes for native-only CTest regression."""
from pathlib import Path
import argparse,hashlib,json
from embed_fixture import write_embedded_arrays

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('oracle',type=Path);p.add_argument('output',type=Path);a=p.parse_args()
    data=json.loads(a.oracle.read_text());fonts=list(dict.fromkeys(r['font']['path'] for r in data['rows']));lines=['// Generated by latin_compat_fixture.py from independent Windows observations.',
        '// Oracle SHA-256: '+hashlib.sha256(a.oracle.read_bytes()).hexdigest()]
    def array(kind,name,values):
        lines.append(f'constexpr {kind} {name}[]{{')
        lines.extend('    '+','.join(str(v) for v in values[i:i+24])+',' for i in range(0,len(values),24));lines.append('};')
    lines.append(write_embedded_arrays(a.output.with_suffix(''),[(f'constexpr u8 latin_compat_font_{i}[]',f'latin_compat_font_{i}',Path(font).read_bytes()) for i,font in enumerate(fonts)]).rstrip('\n'))
    lines.append('constexpr ConstSlice<u8> latin_compat_fonts[]{')
    lines.extend(f'    {{latin_compat_font_{i},sizeof(latin_compat_font_{i})}},' for i in range(len(fonts)));lines.append('};')
    for i,row in enumerate(data['rows']):
        r=row['result'];assert row['exit']==r['hresult']==r['placement_hresult']==0
        array('u16',f'latin_compat_glyphs_{i}',r['glyphs']);array('u32',f'latin_compat_clusters_{i}',r['clusters']);array('u32',f'latin_compat_placement_{i}',sum(r['placement_bits'],[]))
    lines+=['struct LatinCompatibilityCase {u32 font,em,weight;Utf8View text;ConstSlice<u16> glyphs;ConstSlice<u32> clusters,placements;};','constexpr LatinCompatibilityCase latin_compat_cases[]{']
    for i,row in enumerate(data['rows']):
        r=row['result'];encoded=''.join(chr(cp) for cp in row['text']).encode();literal=''.join(f'\\x{b:02x}' for b in encoded)
        lines.append(f'    {{{fonts.index(row["font"]["path"])},{r["em_bits"]},{row["weight"]},{{"{literal}",{len(encoded)}}},{{latin_compat_glyphs_{i},{len(r["glyphs"])}}},{{latin_compat_clusters_{i},{len(r["clusters"])}}},{{latin_compat_placement_{i},{len(r["placement_bits"])*3}}}}},')
    lines+=['};',''];a.output.write_text('\n'.join(lines),encoding='utf-8');print(len(fonts),'fonts;',len(data['rows']),'embedded compatibility cases')
if __name__=='__main__':main()
