"""App symbol/selector inputs; expectations come from the live QA reference."""
from pathlib import Path

texts=['A ❤️ B','A ❤︎ B','❤︎','©︎','®︎','™︎','☀︎','☂︎','☎︎','♥︎ ♦︎ ♣︎ ♠︎',
       'A\ufe0f B','A\U000e0100 B','α\ufe00 Б\ufe0f','á\ufe0f b','\ufe0e','\ufe0f','\U000e0100','A \ufe0f B',
       'x (❤︎) y','x ≤ y ≥ z','∫ ∮ ∲ ∳','(❤︎','❤︎)','A\t❤︎\r\nB','α ❤︎ Б','☕︎ 😀 ★',
       '1\ufe0e\u20e3','❤︎‍🔥','A⃝\ufe0f B','A\ufe0f\ufe0e B',
       'A\u00a0\ufe0f B','A\u2003\ufe0e B','A \ufe0f\ufe0e B','A\ufe0f B',
       '\ufe0f A','A \U000e0100 B','A \ufe0f','A á\ufe0f B']

def main():
    lines=['// Generated by tools/font_reference/generate_symbol_cases.py.','const Utf8View symbol_texts[]{']
    for text in texts:
        lines.append('    utf8_literal("'+''.join('\\x%02x'%b for b in text.encode())+'"),')
    lines.append('};')
    path=Path(__file__).resolve().parents[2]/'tests/native_symbol_inputs.inc'
    path.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print('Wrote',len(texts),'symbol inputs')

if __name__=='__main__':main()
