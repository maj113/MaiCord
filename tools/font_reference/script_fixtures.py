"""QA only: derive the script compatibility delta and replay fixtures.

Inputs are first-party Windows observations and MaiCord's verified Unicode dump.
No font package or production text library is imported. Windows numeric script
IDs are translated through the properties captured by the same analyzer.
"""
import argparse
import array
import hashlib
import json
from pathlib import Path
import re
import struct
import sys

SLOTS = 0x110000
CONTEXTS = (0, 0x61, 0x628, 0x5D0, 0x4E2D, 0x915, 0xE01, 0x3042)


def identity(path):
    data = path.read_bytes()
    return dict(path=str(path.resolve()), bytes=len(data), sha256=hashlib.sha256(data).hexdigest())


def words(data):
    result = array.array('H')
    result.frombytes(data)
    return result


def properties(data, at, names):
    count, = struct.unpack_from('<I', data, at)
    assert 0 < count < 2048 and at + 4 + 20 * count == len(data)
    mapping = []
    for i in range(count):
        iso, = struct.unpack_from('<I', data, at + 4 + 20 * i)
        mapping.append(names.index(iso.to_bytes(4, 'little').decode('ascii').lower()) if iso else None)
    return mapping


def translate(value, mapping):
    if value == 0xFFFF:
        return value
    index = value & 0x7FFF
    assert index < len(mapping) and mapping[index] is not None
    return mapping[index] | (512 if value & 0x8000 else 0)


def generate(args):
    assert sys.byteorder == 'little'
    text = args.unicode_header.read_text()
    block = text.split('enum class UnicodeScript : u8 {', 1)[1].split('};', 1)[0]
    names = re.findall(r'^\s*(\w+)\s*,?\s*$', block, re.M)
    assert 0 < len(names) < 256 and len(set(names)) == len(names)
    ids = {name: i for i, name in enumerate(names)}
    ucd = args.unicode_dump.read_bytes()
    assert ucd[:8] in (b'MCUCD17\0', b'MCUCDS1\0')
    fields, selector = (12, 5) if ucd[:8] == b'MCUCDS1\0' else (14, 9)
    ucd_script, selectors = bytearray(SLOTS), bytearray(SLOTS)
    at = 8
    for cp in range(SLOTS):
        ucd_script[cp] = ucd[at + 2]
        selectors[cp] = bool(struct.unpack_from('<I', ucd, at + fields)[0] & (1 << selector))
        at += fields + 14 + ucd[at + fields + 13] * 4
    assert at == len(ucd)
    data = args.scalars.read_bytes()
    assert struct.unpack_from('<5I', data) == (0x3141534D, 1, len(CONTEXTS), SLOTS, 6)
    assert struct.unpack_from('<8I', data, 20) == CONTEXTS
    at = 52 + SLOTS * 48
    mapping = properties(data, at, names)
    raw = words(data[52:at])
    translated = words(b'')
    translated.extend(translate(v, mapping) for v in raw)
    classes, intrinsic, baseline = words(b''), words(b''), words(b'')
    differences = contextual = nonvisual = 0
    for cp in range(SLOTS):
        first = cp * 24
        row = raw[first:first + 24]
        if 0xD800 <= cp <= 0xDFFF:
            assert all(v == 0xFFFF for v in row)
            classes.append(ids['zzzz'] | 1024)
            intrinsic.append(ids['zzzz']); baseline.append(ids['zzzz'])
            continue
        assert row[0] == row[2] == 0xFFFF
        base = translated[first + 1]
        context = row[4] != row[1]
        hidden = bool(base & 512)
        assert not (context and hidden)
        assert all((row[i * 3 + 1] != row[1]) == context for i in range(1, 8))
        classes.append(base | (256 if context else 0) | (2048 if selectors[cp] else 0))
        actual = base | (256 if context else 0)
        script = ucd_script[cp]
        predicted = ids['zyyy'] | 512 if hidden else ids['zzzz'] | 256 if script in (ids['zyyy'], ids['zinh']) else script | (256 if selectors[cp] else 0)
        intrinsic.append(actual); baseline.append(predicted)
        differences += actual != predicted
        contextual += context
        nonvisual += hidden
    # Extend an override only across identical observed classes. This can merge
    # adjacent mismatch ranges without changing already-correct classifications.
    ranges = []
    first = 0
    for cp in range(1, SLOTS + 1):
        if cp == SLOTS or intrinsic[cp] != intrinsic[first]:
            if intrinsic[first:cp] != baseline[first:cp]:
                value = intrinsic[first]
                assert value < 256 and not any(selectors[first:cp])
                ranges.append((first, cp - 1, value))
            first = cp
    lines = ['// Generated by tools/font_reference/script_fixtures.py.\n',
             '// MaiCord en-US policy; Unicode Script data is unchanged.\n',
             'constexpr ScriptOverride script_overrides[]{\n']
    lines += ['    {0x%xu,0x%xu},\n' % (a, b | (s << 21)) for a, b, s in ranges]
    lines += ['};\nstatic_assert(sizeof(script_overrides)==%d);\n' % (len(ranges) * 8)]
    output = args.output
    output.mkdir(parents=True, exist_ok=True)
    (output / 'script_compat_data.inc').write_text(''.join(lines))
    (output / 'classes.bin').write_bytes(struct.pack('<II', 0x3153434E, SLOTS) + classes.tobytes())
    (output / 'contexts.bin').write_bytes(struct.pack('<11I', 0x3143534E, SLOTS, len(CONTEXTS), *CONTEXTS) + translated.tobytes())
    source, captured = args.sequences.read_bytes(), args.sequence_results.read_bytes()
    assert source[:8] == captured[:8]
    magic, count = struct.unpack_from('<II', source)
    assert magic == 0x3151534D and 0 < count <= 1000000
    at = 8
    rows = []
    for _ in range(count):
        n, = struct.unpack_from('<I', captured, at)
        assert 0 < n <= 4096
        at += 4
        rows.append(words(captured[at:at + n * 2])); at += n * 2
    mapping = properties(captured, at, names)
    at = 8
    resolved = bytearray(struct.pack('<II', 0x3152534E, count))
    for row in rows:
        n, = struct.unpack_from('<I', source, at)
        assert n == len(row)
        resolved += source[at:at + 4 + n * 4]; at += 4 + n * 4
        result = words(b''); result.extend(translate(v, mapping) for v in row)
        assert all(v != 0xFFFF for v in result)
        resolved += result.tobytes()
    assert at == len(source)
    (output / 'resolved.bin').write_bytes(resolved)
    info = dict(inputs=[identity(p) for p in (args.scalars, args.unicode_dump, args.unicode_header, args.sequences, args.sequence_results)],
                scripts=names, differences=differences, contextual=contextual, nonvisual=nonvisual,
                override_ranges=ranges, table_bytes=len(ranges) * 8, scalar_calls=(SLOTS - 2048) * 8,
                sequence_cases=count, sequence_scalars=sum(map(len, rows)))
    info['outputs'] = [identity(output / p) for p in ('script_compat_data.inc', 'classes.bin', 'contexts.bin', 'resolved.bin')]
    (output / 'script-fixtures.json').write_text(json.dumps(info, indent=2))
    print('PASS script fixture generation:', info['scalar_calls'], 'scalar calls,', count, 'strings,', info['table_bytes'], 'table bytes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('scalars', 'unicode-dump', 'unicode-header', 'sequences', 'sequence-results', 'output'):
        parser.add_argument('--' + name, type=Path, required=True)
    generate(parser.parse_args())
