"""Authored Tibetan preparation inputs; expected boundaries come from Windows."""
import itertools,random
ALPHABET=(0xf40,0xf68,0xf20,0xf0b,0xf18,0xf35,0xf39,0xf3e,0xf71,0xf72,0xf73,0xf74,
          0xf75,0xf76,0xf77,0xf7e,0xf7f,0xf82,0xf84,0xf86,0xf90,0xfb2,0xfc6,
          0x200c,0x200d,0x34f,0xfe00,0xfe01,0xa0,0x25cc,0x20)
def corpus(stress=False):
    cases={}
    def add(values,group):
        values=tuple(values)
        if values:cases.setdefault(values,group)
    for c in range(0xf00,0x1000):
        for prefix in ((),(0xf40,),(0xf90,),(0xf20,),(0xf40,0xf90),(0xf40,0xf71)):
            add((*prefix,c),'scalar-coverage')
        add((c,0xf90,0xf72),'scalar-tail')
    for prefix in ((),(0xf40,),(0xf20,),(0x25cc,),(0xf40,0xf90),(0xf40,0xf39),(0xf72,)):
        for pair in itertools.product(ALPHABET,repeat=2):add((*prefix,*pair),'pairs')
    for word in 'བོད་ཡིག བཀྲ་ཤིས་བདེ་ལེགས བསྒྲུབས ཨོཾ'.split():
        for end in range(1,len(word)+1):add(map(ord,word[:end]),'partial-word')
    for c in ALPHABET:
        for n in (29,30,31,32,33,63,100,200):add((0xf40,)+(c,)*n,'long')
    for head in (0xf40,0xf20,0xf90,0xf72,0xf0b,0x20,0x24,0xa0,0x25cc,0xfff):
        for selector in (0xfe00,0xfe01,0xe0100,0x1f600):
            add((head,selector,0xf72),'selectors');add((head,selector,selector,0x200d),'selectors')
    rng=random.Random(60022)
    for _ in range(20000 if stress else 3000):add((rng.choice(ALPHABET) for i in range(rng.randint(1,24))),'random')
    if stress:
        for prefix in ((0xf40,0xf39,0xf35),(0xf40,0xf90,0xf39),(0xf40,0xf72,0xf71),
                       (0xf40,0xf7e),(0xf40,0xf7f),(0xf40,0xf84)):
            for pair in itertools.product(ALPHABET,repeat=2):add((*prefix,*pair),'deep-tail')
        for selector in (0xfe00,0xfe0f,0xe0100,0xe01ef):
            for sign in (0xf90,0xf39,0xf71,0xf72,0xf77,0x34f,0x200d):
                for n in (14,15,16,29,30,31,32,33,63):
                    add((0xf40,)+(sign,selector)*n+(0xf40,),'long-selectors')
            for previous in (0xfe00,0xfe0f,0xe0100,0xe01ef):
                for head in (0xf40,0xf72,0xf0b,0x200c,0x20,0x24,0xfff):
                    add((head,previous,selector,0x200d,0x34f,0xf72),'selector-controls')
        for head in (0x2d,0xd7,0x2012,0x2013,0x2014,0x2015,0x2022,0x25fb,0x25fc,0x25fd,0x25fe,
                     0x41,0x301,0x327,0x2060,0xfeff,0x1f600):
            for pair in itertools.product(ALPHABET,repeat=2):add((head,*pair),'common-pairs')
    return list(cases.items())

def make_font(path):
    from myanmar_input_font import make_font as identity_font
    common=[0x20,0x24,0x2d,0x41,0xa0,0xd7,0x34f,0x200c,0x200d,0x2012,0x2013,0x2014,0x2015,0x2022,0x25cc,0x25fb,0xfe00,0xfe01,0xe0100,0x1f600,0x2060]
    return identity_font(path,script_tag='tibt',scalars=list(range(0xf00,0x1000))+common,base=0xf40,label='Tibetan')
