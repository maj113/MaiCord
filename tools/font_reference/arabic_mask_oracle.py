"""First-party Windows probes for form eligibility on GSUB matched inputs."""
import argparse,json,subprocess
from pathlib import Path
from fontTools.ttLib import TTFont,newTable
from arabic_joining_oracle import make
from feature_plan_oracle import layout,language,script
from gsub_execution_oracle import lookup,single,ligature,context,obj,coverage,identity

def scenarios():
    b='u0628';out=b+'_init';tag=lookup(1,single({b:out}))
    yield 'init-single','init',[tag]
    yield 'init-multiple','init',[lookup(2,obj('MultipleSubst',mapping={b:[out,b+'_medi']}))]
    yield 'init-alternate','init',[lookup(3,obj('AlternateSubst',alternates={b:[out,b+'_medi']}))]
    yield 'init-ligature','init',[ligature([b,b],out)]
    yield 'medi-ligature','medi',[ligature([b,b],out)]
    yield 'init-context','init',[context([b,b],[(1,1)]),tag]
    yield 'medi-context','medi',[context([b,b],[(1,1)]),tag]
    yield 'init-lookahead','init',[context([b],[(0,1)],chained=True,ahead=[b]),tag]
    yield 'fina-backtrack','fina',[context([b],[(0,1)],chained=True,back=[b]),tag]
    yield 'init-nested-ligature','init',[context([b],[(0,1)],chained=True,ahead=[b]),ligature([b,b],out)]
    yield 'medi-nested-ligature','medi',[context([b,b],[(1,1)]),ligature([b,b],out)]
    yield 'init-reverse-lookahead','init',[lookup(8,obj('ReverseChainSingleSubst',Format=1,Coverage=coverage([b]),BacktrackGlyphCount=0,BacktrackCoverage=[],LookAheadGlyphCount=1,LookAheadCoverage=[coverage([b])],GlyphCount=1,Substitute=[out]))]
    # Rejecting the first (longer) candidate must not hide a later valid rule.
    long=ligature([b,b,b],out).SubTable[0];short=ligature([b,b],b+'_medi').SubTable[0]
    long.ligatures[b]+=short.ligatures[b]
    yield 'medi-later-ligature','medi',[lookup(4,long)]
    yield 'medi-skip-mark','medi',[ligature([b,b],out,flags=8)]
    yield 'liga-skip-mark','liga',[ligature([b,b],out,flags=8)]
    yield 'medi-context-skip-mark','medi',[context([b,b],[(0,1)],flags=8),tag]
    yield 'medi-lookahead-mark','medi',[context([b],[(0,1)],flags=8,chained=True,ahead=[b]),tag]
    yield 'medi-nested-mark','medi',[context([b,b],[(0,1)],flags=8),ligature([b,'u064e'],out)]
    for fmt in [1,2]:
        for later in [False,True]:
            rules=[]
            for count,child in ([(3,1),(2,2)] if later else [(2,1)]):
                fields=dict(GlyphCount=count,SubstCount=1,SubstLookupRecord=[obj('SubstLookupRecord',SequenceIndex=0,LookupListIndex=child)])
                fields['Input' if fmt==1 else 'Class']=[b if fmt==1 else 1]*(count-1)
                rules.append(obj('SubRule' if fmt==1 else 'SubClassRule',**fields))
            if fmt==1:sub=obj('ContextSubst',Format=1,Coverage=coverage([b]),SubRuleSetCount=1,SubRuleSet=[obj('SubRuleSet',SubRuleCount=len(rules),SubRule=rules)])
            else:sub=obj('ContextSubst',Format=2,Coverage=coverage([b]),ClassDef=obj('ClassDef',classDefs={b:1}),SubClassSetCount=2,SubClassSet=[None,obj('SubClassSet',SubClassRuleCount=len(rules),SubClassRule=rules)])
            yield f'medi-context{fmt}-later{int(later)}','medi',[lookup(5,sub),tag,lookup(1,single({b:b+'_medi'}))]

def run(root,exe):
    root.mkdir(parents=True,exist_ok=True);cases=[]
    for name,feature,lookups in scenarios():
        path=root/(name+'.ttf');order=make(path);font=TTFont(path,recalcTimestamp=False)
        font['GSUB']=newTable('GSUB');font['GSUB'].table=layout('GSUB',[(feature,[0])],lookups,{'arab':script(language([0]))})
        font['GDEF']=newTable('GDEF');font['GDEF'].table=obj('GDEF',Version=0x10000,GlyphClassDef=obj('ClassDef',classDefs={n:3 if n=='u064e' else 1 for n in order}),AttachList=None,LigCaretList=None,MarkAttachClassDef=None)
        font.save(path)
        for length in [1,2,3,4,5]:
            scalars=[0x628]*length
            if 'mark' in name and length>=2:scalars.insert(2,0x64e)
            p=subprocess.run([str(exe),str(path),','.join(f'{c:x}' for c in scalars),'default','1148846080','1','0','en-US'],capture_output=True,text=True,timeout=15,creationflags=0x08000000)
            assert p.returncode==0,(name,length,p.stdout,p.stderr)
            result=json.loads(p.stdout);assert result['hresult']==0 and result['placement_hresult']==0
            cases.append(dict(name=name,font=identity(path),feature=feature,scalars=scalars,result=result))
            print(name,length,[order[g] for g in result['glyphs']])
    (root/'observations.json').write_text(json.dumps(dict(reference=identity(exe),glyph_order=order,cases=cases),indent=2))

def fixture(root,destination):
    data=json.loads((root/'observations.json').read_text());lines=['// First-party Windows form-feature probes; generated by arabic_mask_oracle.py.',
        '// Reference SHA256: '+data['reference']['sha256']];fonts={};cases=[]
    def array(name,kind,values):
        lines.append(f'constexpr {kind} {name}[]{{')
        lines.extend('    '+','.join(f'0x{v:x}' for v in values[i:i+16])+',' for i in range(0,len(values),16));lines.append('};')
    for i,c in enumerate(data['cases']):
        name=c['name']
        if name not in fonts:
            fidx=len(fonts);fonts[name]=fidx;path=root/(name+'.ttf')
            assert identity(path)['sha256']==c['font']['sha256']
            font=TTFont(path)
            array(f'arabic_mask_gsub_{fidx}','u8',font.getTableData('GSUB'))
            array(f'arabic_mask_gdef_{fidx}','u8',font.getTableData('GDEF'))
        fidx=fonts[name];array(f'arabic_mask_input_{i}','u32',c['scalars']);array(f'arabic_mask_expected_{i}','u16',c['result']['glyphs'])
        mask={'isol':1,'fina':2,'medi':4,'init':8,'liga':0}[c['feature']]
        cases.append(f'    {{{{arabic_mask_gsub_{fidx},sizeof(arabic_mask_gsub_{fidx})}},{{arabic_mask_gdef_{fidx},sizeof(arabic_mask_gdef_{fidx})}},{{arabic_mask_input_{i},{len(c["scalars"])} }},{{arabic_mask_expected_{i},{len(c["result"]["glyphs"])} }},{mask}}}, // {name}')
    lines.extend(['constexpr ArabicMaskCase arabic_mask_cases[]{',*cases,'};',''])
    destination.write_text('\n'.join(lines));print(len(cases),'mask fixtures')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('root',type=Path);p.add_argument('--exe',type=Path);p.add_argument('--fixture',type=Path);a=p.parse_args()
    if a.fixture:fixture(a.root.resolve(),a.fixture)
    else:
        if not a.exe:p.error('--exe is required for capture')
        run(a.root.resolve(),a.exe.resolve())
