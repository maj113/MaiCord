"""Small OpenType UVS fixture with HarfBuzz expectations; FontTools and uharfbuzz are QA-only generation dependencies."""
import struct
from pathlib import Path
from io import BytesIO
import uharfbuzz as hb
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib.tables._c_m_a_p import CmapSubtable
from embed_fixture import embed_arrays, write_if_changed


def shape(blob, text, rtl):
    """HarfBuzz's (glyphs, advance bits at 15.625 px, first glyph per UTF-16 unit) in logical order. Right to left
    shapes as Hebrew, which HarfBuzz does not reverse; the font has no layout tables a script would select."""
    font = hb.Font(hb.Face(hb.Blob(blob)))
    buffer = hb.Buffer()
    buffer.add_codepoints([ord(c) for c in text])
    buffer.direction, buffer.script, buffer.language = ('rtl', 'Hebr', 'en') if rtl else ('ltr', 'Latn', 'en')
    hb.shape(font, buffer, {})
    infos, positions = list(buffer.glyph_infos), list(buffer.glyph_positions)
    if rtl:
        infos.reverse()
        positions.reverse()
    first = {}
    for index, info in enumerate(infos):
        first.setdefault(info.cluster, index)
    starts = sorted(first)
    sources = []
    for index, c in enumerate(text):
        sources += [first[max(s for s in starts if s <= index)]] * (2 if ord(c) > 0xFFFF else 1)
    advances = [struct.unpack('<I', struct.pack('<f', p.x_advance * 15.625 / 1000))[0] for p in positions]
    return [info.codepoint for info in infos], advances, sources

def main():
    names=['.notdef','space','A','B','A.alt','alef','alef.alt','paren.left','paren.right','less','greater','Aacute','acute','acute.alt']
    builder=FontBuilder(1000,isTTF=True)
    builder.setupGlyphOrder(names)
    builder.setupCharacterMap({32:'space',65:'A',66:'B',0x5d0:'alef',40:'paren.left',41:'paren.right',60:'less',62:'greater',0xc1:'Aacute',0x301:'acute'})
    glyphs={}
    for name in names:
        pen=TTGlyphPen(None)
        if name!='space':
            pen.moveTo((50,0));pen.lineTo((400,0));pen.lineTo((400,600));pen.lineTo((50,600));pen.closePath()
        glyphs[name]=pen.glyph()
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({n:(500+100*i,0) for i,n in enumerate(names)})
    builder.setupHorizontalHeader(ascent=800,descent=-200)
    builder.setupNameTable({'familyName':'MaiCord Variation QA','styleName':'Regular','uniqueFontIdentifier':'MaiCord Variation QA 1','fullName':'MaiCord Variation QA','psName':'MaiCordVariationQA'})
    builder.setupOS2(sTypoAscender=800,sTypoDescender=-200,usWinAscent=800,usWinDescent=200)
    builder.setupPost();builder.setupMaxp()
    variation=CmapSubtable.newSubtable(14);variation.platformID=0;variation.platEncID=5;variation.language=0;variation.cmap={}
    variation.uvsDict={0x180b:[(65,'A.alt')],0xfe0f:[(65,'A.alt'),(66,None),(0x301,'acute.alt'),(0x5d0,'alef.alt')],0xe0100:[(65,'A.alt'),(0x301,None)]}
    builder.font['cmap'].tables.append(variation)
    builder.font['head'].created=builder.font['head'].modified=3400000000
    builder.font.recalcTimestamp=False;stream=BytesIO();builder.font.save(stream)
    rows=['// Generated by tools/font_reference/generate_text_variation_fixture.py; HarfBuzz '+hb.version_string()+' expectations.']
    blob=stream.getvalue()
    path=Path(__file__).resolve().parents[2]/'tests/generated/text_variation_fixture.inc'
    write_if_changed(path.with_suffix('.bin'),blob)
    rows.append(embed_arrays([('constexpr u8 text_variation_font[]',path.stem+'.bin')]).rstrip('\n'))
    texts=['A\ufe0fB','A\ufe0eB','A\U000e0100B','A\U000e01efB','A\u180bB','א\ufe0fB','A\ufe0fB\ufe0fA\U000e0100','(',')','<A>','(\ufe0fA)']
    profiles=[7]*len(texts)
    texts+=['A\u0301\ufe0e','A\u0301\ufe0f','A\u0301\U000e0100','A\ufe0f\u0301','A\ufe0f\ufe0e']
    profiles+=[2]*5
    cases=[]
    for i,text in enumerate(texts):
        glyphs,advances,sources=shape(blob,text,False)
        rtl,rtl_advances,rtl_sources=shape(blob,text,True)
        assert len(rtl)==len(glyphs) and rtl_sources==sources
        rows.append(f'constexpr u16 variation_glyphs_{i}[]{{'+','.join(map(str,glyphs))+'};')
        rows.append(f'constexpr u16 variation_rtl_{i}[]{{'+','.join(map(str,rtl))+'};')
        rows.append(f'constexpr u32 variation_advances_{i}[]{{'+','.join(map(str,advances))+'};')
        rows.append(f'constexpr u32 variation_rtl_advances_{i}[]{{'+','.join(map(str,rtl_advances))+'};')
        rows.append(f'constexpr u32 variation_sources_{i}[]{{'+','.join(map(str,sources))+'};')
        cases.append((text,len(glyphs),len(sources)))
    rows.append('struct TextVariationCase {Utf8View text;ConstSlice<u16> glyphs,rtl;ConstSlice<u32> advances,rtl_advances,sources;u32 profiles;};')
    rows.append('constexpr TextVariationCase text_variation_cases[]{')
    for i,(text,glyphs,sources) in enumerate(cases):
        escaped=''.join('\\x%02x'%b for b in text.encode())
        rows.append(f'    {{utf8_literal("{escaped}"),{{variation_glyphs_{i},{glyphs}}},{{variation_rtl_{i},{glyphs}}},'
                    f'{{variation_advances_{i},{glyphs}}},{{variation_rtl_advances_{i},{glyphs}}},{{variation_sources_{i},{sources}}},{profiles[i]}}},')
    rows.append('};')
    write_if_changed(path,('\n'.join(rows)+'\n').encode('utf-8'))
    print('Wrote',len(blob),'font bytes and',len(cases),'variation cases')

if __name__=='__main__':main()
