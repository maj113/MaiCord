"""Extract polygon and isolated quadratic points from Windows QA captures.

The widening model is not used. Contour direction is explicit
test input; these fixtures test arithmetic, not the unfinished classifier.
"""
import argparse, hashlib, json, struct
from pathlib import Path
from fontTools.ttLib import TTFont
from bold_app_points_oracle import emit,bits
from embed_fixture import write_embedded_array

def curve_points(commands,units):
    result=[];current=None
    for c in commands:
        v=c['design_coordinates'];kind=c['kind']
        if kind in (0,2):current=tuple(round(x*64)/64 for x in v[:2]);result.append(current)
        elif kind==3:
            control=tuple(round((3*v[j]-current[j])*32)/64 for j in range(2))
            current=tuple(round(x*64)/64 for x in v[4:6]);result.extend([control,current])
        else:assert kind==5
    flags=[1,0,1,1,0,1];assert len(result)==6
    # Recovering the controls is accepted only if it reproduces every captured
    # cubic command bit, using the independently verified native emitter model.
    actual=emit([[(*p,f) for p,f in zip(result,flags)]],units,0)
    expected=[]
    for c in commands:
        expected.extend(bits(v/units*(-1 if i%2 else 1)) for i,v in enumerate(c['design_coordinates']))
        expected.append(c['kind'])
    assert actual==expected
    return result

def direction(contours):
    choices=[(p[0],-p[1],c,i) for c,ps in enumerate(contours) if len(set(ps))>2 for i,p in enumerate(ps)]
    if not choices:return 0
    _,_,c,i=min(choices);ps=contours[c];p=ps[i];a=(i-1)%len(ps);b=(i+1)%len(ps)
    while ps[a]==p:a=(a-1)%len(ps)
    while ps[b]==p:b=(b+1)%len(ps)
    return int((p[0]-ps[a][0])*(ps[b][1]-p[1])-(p[1]-ps[a][1])*(ps[b][0]-p[0])>0)

def run(inputs,output):
    rows=[];count=0
    for source in inputs:
        data=json.loads(source.read_text())
        for case in data['cases']:
            path=Path(case['font']['path'])
            assert hashlib.sha256(path.read_bytes()).hexdigest()==case['font']['sha256']
            font=TTFont(path);units=case['units']
            for name in case.get('directions',font.getGlyphOrder()):
                points,ends,flags=font['glyf'][name].getCoordinates(font['glyf'])
                if not points:continue
                curved=any(not(f&1) for f in flags)
                if curved and not name.startswith('quadratic'):continue
                contours=[];start=0
                for end in ends:contours.append([tuple(p) for p in points[start:end+1]]);start=end+1
                # Isolated single-point contours have no outline command.
                if any(len(c)==1 for c in contours):continue
                if 'directions' in case:
                    expected=[(p[0]+d[0],p[1]+d[1]) for p,d in zip(points,case['directions'][name]['displacements'])]
                elif curved:expected=curve_points(case['outlines']['1'][name],units)
                else:expected=[tuple(round(v*64)/64 for v in c['design_coordinates'][:2]) for c in case['outlines']['1'][name] if c['kind']!=5]
                assert len(points)==len(expected)
                row=struct.pack('<4I',units,len(points),len(ends),direction(contours)|(int(case.get('fractional_halves',False))<<8))
                row+=b''.join(struct.pack('<I',e) for e in ends)
                row+=b''.join(struct.pack('<4i',round(p[0]*64),round(p[1]*64),round(e[0]*64),round(e[1]*64)) for p,e in zip(points,expected))
                rows.append(row);count+=len(points)
    payload=struct.pack('<I',len(rows))+b''.join(rows)
    provenance='\n'.join(f'// {p.name}: SHA256 {hashlib.sha256(p.read_bytes()).hexdigest()}' for p in inputs)
    write_embedded_array(output,'// Generated by bold_points_fixture.py; first-party shapes, Windows expected points.\n'+provenance+'\n','static constexpr u8 bold_points_fixture[]',payload)
    print(json.dumps(dict(cases=len(rows),points=count,bytes=len(payload),sha256=hashlib.sha256(payload).hexdigest())))

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('inputs',nargs='+',type=Path);p.add_argument('--output',required=True,type=Path);a=p.parse_args();run(a.inputs,a.output)
