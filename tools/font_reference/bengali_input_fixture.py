"""Freeze verified Indic scanner vectors as scalar/flag records for offline tests."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--script',choices=('bengali','gujarati','gurmukhi','odia','telugu','kannada','malayalam'),default='bengali')
    parser.add_argument('--forms-report',type=Path,help='Verified face-zero form observations required for Telugu/Kannada/Malayalam')
    parser.add_argument('--deduplicate',action='store_true',help='Store each identical scalar/boundary vector once')
    parser.add_argument('--report',type=Path,action='append',required=True)
    parser.add_argument('--output',type=Path)
    args=parser.parse_args()
    if args.output is None:args.output=Path('tests/generated')/(args.script+'_input_fixture.inc')
    records=[]; cases=0; unavailable=0; origins=[]; seen_vectors={}; first_inputs=None
    for path in args.report:
        raw=path.read_bytes(); report=json.loads(raw)
        if report['status'] not in ('passed','incomplete') or report['mismatches']:
            raise ValueError('A report with unresolved differences cannot freeze expectations')
        origins.append(hashlib.sha256(raw).hexdigest())
        if args.deduplicate:
            if first_inputs is None:first_inputs=report['inputs']
            elif first_inputs!=report['inputs']:raise ValueError('Cannot merge different fonts or observers')
        for row in report['rows']:
            if row['exact'] is None:
                if 'unavailable' not in row:
                    raise ValueError('Unexplained unavailable row')
                unavailable+=1;continue
            if row['exact'] is not True or row['native']!=row['expected'] or len(row['scalars'])!=len(row['expected']) or not 0<len(row['scalars'])<=256:
                raise ValueError('Invalid verified vector')
            if args.deduplicate:
                key=tuple(row['scalars'])
                if key in seen_vectors:
                    if seen_vectors[key]!=row['expected']:raise ValueError('Contradictory frozen expectations')
                    continue
                seen_vectors[key]=row['expected']
            for i,(scalar,start) in enumerate(zip(row['scalars'],row['expected'])):
                if start not in (0,1) or not 0<=scalar<=0x10ffff or 0xd800<=scalar<=0xdfff:
                    raise ValueError('Invalid scalar/flag')
                records.append(scalar|(start<<31)|(int(i+1==len(row['scalars']))<<30))
            cases+=1
    lines=['// First-party scalar corpus and Windows-observed source boundaries; no font bytes.',
        '// Generated by tools/font_reference/bengali_input_fixture.py.',
        f'// {unavailable} unavailable Windows cases remain outside acceptance.']
    lines.extend('// Report SHA-256: '+value for value in origins)
    if args.script in ('telugu','kannada','malayalam'):
        block=0xd00 if args.script=='malayalam' else 0xc80 if args.script=='kannada' else 0xc00
        if not args.forms_report:raise ValueError('This fixture needs verified font-form observations')
        raw=args.forms_report.read_bytes();forms=json.loads(raw)
        if forms['status']!='passed':raise ValueError('Unverified form observations')
        bits=[0]*128;seen=set()
        for row in forms['checks']:
            if row['kind']!='form' or row['face']!=0:continue
            if not row['exact']:raise ValueError('Unmatched form observation')
            scalar=row['scalar'];mask={'rphf':2,'half':8,'pref':16,'blwf':4,'pstf':32}[row['feature']]
            if not block<=scalar<block+128:raise ValueError('Form scalar outside selected script')
            seen.add(mask)
            if len(row['reference_glyphs'])==1:bits[scalar-block]|=mask
        if seen!={2,8,16,4,32}:raise ValueError('Missing form classes')
        lines.append('// Form observations SHA-256: '+hashlib.sha256(raw).hexdigest())
        lines.append('constexpr u8 '+args.script+'_input_forms[128]{'+','.join(map(str,bits))+'};')
    resource_id=1001+('bengali','gujarati','gurmukhi','odia','telugu','kannada','malayalam').index(args.script)
    payload=struct.pack('<'+'I'*len(records),*records)
    lines.extend([f'constexpr u32 {args.script}_input_fixture_cases={cases};',
        '// Resource SHA-256: '+hashlib.sha256(payload).hexdigest(),
        f'constexpr u32 {args.script}_input_fixture_words={len(records)};',
        f'constexpr u16 {args.script}_input_fixture_resource={resource_id};'])
    args.output.with_suffix('.bin').write_bytes(payload)
    args.output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(f'Wrote {cases} cases; {len(records)*4} QA-only bytes; {unavailable} unavailable cases preserved in reports')

if __name__=='__main__':
    main()
