"""Generate src/text/generated/fallback_compat_data.inc from observed classes.

The table holds the en-US font fallback attachment classes that differ from
the Unicode default (General_Category Mn/Mc/Me extends, Variation_Selector
extends as a selector), as read by native_font_fallback_class.

Observation, public API only: IDWriteFontFallback::MapCharacters through
font_fallback_reference.cpp, with two controlled probe fonts whose cmaps cover
complementary scalars, sweeping every scalar X in the contexts base+X and
base+X+next. X is extending (1) when it keeps the preceding fallback face
whenever that face covers X, joining (2) when the next scalar keeps the face
X used, and a selector (4) when it keeps the preceding face without coverage.
The sweep result is --classes: one class byte per code point, U+0000 to
U+10FFFF, 8 for surrogates. Windows 10.0.29648 produced the checked-in table.

    python -I tools/font_reference/fallback_compat_data.py --classes <classes.bin> --ucd <UCD.zip>
"""
import argparse
import hashlib
from pathlib import Path
import zipfile

LIMIT = 0x110000
EXPECTED_UCD_SHA256 = '2066d1909b2ea93916ce092da1c0ee4808ea3ef8407c94b4f14f5b7eb263d28e'
OUTPUT = Path(__file__).resolve().parents[2] / 'src/text/generated/fallback_compat_data.inc'
EXTENDING, SELECTOR, INVALID = 1, 4, 8


def surrogate(cp):
    return 0xD800 <= cp <= 0xDFFF


def defaults(marks, selectors):
    """Unicode default class per code point; marks and selectors are sets."""
    result = bytearray(LIMIT)
    for cp in range(LIMIT):
        if surrogate(cp):
            result[cp] = INVALID
        elif cp >= 0x300 and cp in selectors:
            result[cp] = EXTENDING | SELECTOR
        elif cp >= 0x300 and cp in marks:
            result[cp] = EXTENDING
    return result


def overrides(observed, default, selectors):
    """Runs of code points whose observed class differs, split where it changes."""
    for cp in range(LIMIT):
        if (cp < 0x300 or cp in selectors or surrogate(cp)) and observed[cp] != default[cp]:
            raise ValueError(f'U+{cp:04X}: class {observed[cp]} is outside the override range')
    ranges = []
    for cp in range(0x300, LIMIT):
        if observed[cp] == default[cp] or cp in selectors or surrogate(cp):
            continue
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == observed[cp]:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, observed[cp]])
    return ranges


def emit(ranges):
    lines = ['// Generated by tools/font_reference/fallback_compat_data.py; do not edit.',
             '// Observed en-US fallback attachment classes that differ from Unicode 17.',
             'constexpr FallbackOverride fallback_overrides[]{']
    lines += [f'    {{0x{first:x}u,0x{last | value << 21:x}u}},' for first, last, value in ranges]
    return '\n'.join(lines + ['};']) + '\n'


def property_set(text, wanted):
    result = set()
    for line in text.splitlines():
        fields = [v.strip() for v in line.split('#', 1)[0].split(';')]
        if len(fields) >= 2 and fields[1] in wanted:
            lo, _, hi = fields[0].partition('..')
            result.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--classes', required=True, type=Path)
    parser.add_argument('--ucd', required=True, type=Path, help='Unicode 17.0.0 UCD.zip')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    observed = args.classes.read_bytes()
    if len(observed) != LIMIT:
        raise ValueError('Expected one class byte per code point')
    data = args.ucd.read_bytes()
    if hashlib.sha256(data).hexdigest() != EXPECTED_UCD_SHA256:
        raise ValueError('UCD archive does not match the pinned Unicode 17.0.0 release')
    with zipfile.ZipFile(args.ucd) as archive:
        marks = property_set(archive.read('extracted/DerivedGeneralCategory.txt').decode(), {'Mn', 'Mc', 'Me'})
        selectors = property_set(archive.read('PropList.txt').decode(), {'Variation_Selector'})
    ranges = overrides(observed, defaults(marks, selectors), selectors)
    args.output.write_bytes(emit(ranges).encode('utf-8'))


if __name__ == '__main__':
    main()
