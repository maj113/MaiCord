"""Embed one first-party Latin preprocessing font for native-only guard tests."""
from pathlib import Path
import argparse, hashlib
from embed_fixture import write_embedded_arrays

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('font',type=Path);p.add_argument('output',type=Path);p.add_argument('--composites-font',required=True,type=Path);a=p.parse_args()
    data=a.font.read_bytes();coverage=a.composites_font.read_bytes()
    lines=['// QA-only first-party cmap fixture. Generated by latin_guard_fixture.py.',
           '// SHA-256: '+hashlib.sha256(data).hexdigest(),
           '// Composite-only coverage SHA-256: '+hashlib.sha256(coverage).hexdigest(),
           write_embedded_arrays(a.output.with_suffix(''),[('constexpr u8 latin_guard_font[]','latin_guard_font',data),
                                                          ('constexpr u8 latin_coverage_font[]','latin_coverage_font',coverage)]).rstrip('\n')]
    a.output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
if __name__=='__main__':main()
