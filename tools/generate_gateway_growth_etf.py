"""Writes tests/fixtures/gateway_growth_etf.hpp: the payloads of
tests/fixtures/gateway_growth.hpp as the user Gateway sends them, ETF terms
(atom keys, nil atoms) in zstd-stream messages (one context per connection,
a flush per message; Python 3.14 compression.zstd).

Usage: python -I tools/generate_gateway_growth_etf.py
"""
import json, pathlib, re, struct, zlib
from compression.zstd import ZstdCompressor, CompressionParameter as P

root = pathlib.Path(__file__).resolve().parent.parent
source = (root / 'tests/fixtures/gateway_growth.hpp').read_text()
arrays = dict(re.findall(r'inline constexpr u8 (kGateway\w+)\[\]\s*=?\s*\{(.*?)\};', source, re.S))


def payload(name, inflater):
    data = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', arrays[name]))
    return inflater.decompress(data)


def term(value, out):
    if value is None:
        out += b'\x64\x00\x03nil'
    elif value is True or value is False:
        text = b'true' if value else b'false'
        out += struct.pack('>BH', 100, len(text)) + text
    elif isinstance(value, int):
        if 0 <= value <= 255:
            out += struct.pack('>BB', 97, value)
        elif -2**31 <= value < 2**31:
            out += struct.pack('>Bi', 98, value)
        else:
            digits = abs(value).to_bytes((abs(value).bit_length() + 7) // 8, 'little')
            out += struct.pack('>BBB', 110, len(digits), value < 0) + digits
    elif isinstance(value, str):
        data = value.encode()
        out += struct.pack('>BI', 109, len(data)) + data
    elif isinstance(value, list):
        if value:
            out += struct.pack('>BI', 108, len(value))
            for item in value:
                term(item, out)
        out += b'\x6a'
    elif isinstance(value, dict):
        out += struct.pack('>BI', 116, len(value))
        for key, item in value.items():
            out += struct.pack('>BH', 100, len(key)) + key.encode('latin-1')
            term(item, out)
    else:
        raise TypeError(type(value))


def etf(text):
    out = bytearray(b'\x83')
    term(json.loads(text), out)
    return bytes(out)


def stream():
    return ZstdCompressor(options={P.compression_level: 3, P.window_log: 16})


inflater = zlib.decompressobj()
connection = stream()
messages = {}
for name in ('kGatewayGrowthHello', 'kGatewayGrowthReady', 'kGatewayGrowthFollow'):
    messages[name + 'Etf'] = connection.compress(etf(payload(name, inflater)), mode=ZstdCompressor.FLUSH_BLOCK)
# Not a term: its 8 MiB output fails the decoded-size bound before transcoding.
messages['kGatewayGrowthBoundEtf'] = stream().compress(payload('kGatewayGrowthBound', zlib.decompressobj()),
                                                         mode=ZstdCompressor.FLUSH_BLOCK)
for name in ('kGatewayGrowthExactIndex', 'kGatewayGrowthExcessIndex'):
    messages[name + 'Etf'] = stream().compress(etf(payload(name, zlib.decompressobj())), mode=ZstdCompressor.FLUSH_BLOCK)

lines = ['// Generated by tools/generate_gateway_growth_etf.py from gateway_growth.hpp; synthetic data only.',
         '#pragma once', '#include "maicord/core/slice.hpp"', 'namespace maicord {']
for name, data in messages.items():
    lines.append(f'inline constexpr u8 {name}[] = {{')
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    lines.append('};')
lines.append('} // namespace maicord')
(root / 'tests/fixtures/gateway_growth_etf.hpp').write_text('\n'.join(lines) + '\n', newline='\n')
print({name: len(data) for name, data in messages.items()})
