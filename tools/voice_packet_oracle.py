"""Generate small independent transport packet vectors (QA dependencies only)."""
import argparse
from pathlib import Path
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from nacl.bindings import crypto_aead_xchacha20poly1305_ietf_encrypt

# Full plaintext packet, clear AAD length, transmitted counter. The cases include
# extension contents, CSRCs, RTP padding, RTCP compound feedback and empty bodies.
PACKETS = (
    ('80780001000003c001020304f8fffe', 12, 0),
    ('b2e7fffeffffffff10203040deadbeefcafebabebede0002'
     '107f900100000000fafa0102030405000003', 24, 1),
    ('80c80006010203040000000000000000000000000000000000000000'
     '81cd000301020304deadbeefffff0001', 8, 0x12345678),
    ('a1cd000401020304deadbeef0001000000000004', 8, 0xfffffffe),
    ('80c9000101020304', 8, 0xffffffff),
)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    key = bytes(range(32))
    lines = ['// Generated by tools/voice_packet_oracle.py using OpenSSL/libsodium.',
             'struct VoicePacketVector { const char* plain; const char* aes; const char* xchacha;',
             '    u32 clear_bytes, counter; };', 'constexpr VoicePacketVector packet_vectors[]{']
    for plain_hex, clear, counter in PACKETS:
        plain = bytes.fromhex(plain_hex)
        suffix = counter.to_bytes(4, 'big')
        aad, body = plain[:clear], plain[clear:]
        aes = aad + AESGCM(key).encrypt(suffix + bytes(8), body, aad) + suffix
        xchacha = aad + crypto_aead_xchacha20poly1305_ietf_encrypt(body, aad, suffix + bytes(20), key) + suffix
        lines.append(f'    {{"{plain_hex}",\n     "{aes.hex()}",\n     "{xchacha.hex()}", {clear}, {counter}u}},')
    lines.append('};')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Generated {len(PACKETS)} packet fixtures for both ciphers: {args.output}')


if __name__ == '__main__':
    main()
