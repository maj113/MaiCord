"""Derive the Tibetan shaping categories (U+0F00..U+0FFF) from the pinned UCD.

Inputs: the Unicode 17.0.0 UCD archive (the same pinned file as generate.py):
IndicSyllabicCategory, IndicPositionalCategory, General_Category, canonical
combining classes and decompositions. Nothing else is read.

Categories follow the Indic syllabic category; dependent vowels take a slot
from their canonical combining class (129 a-chung, 130 the i/e/o signs, 132
u), so canonical order is cluster order, and the two-part vowels split
(canonical decomposition) or stay compound (compatibility decomposition).
Marks with no syllabic category take their position; Lo and So characters
are bases and symbols; everything else is other.

    python -I tools/unicode/tibetan_categories.py --ucd <UCD.zip>
"""
import argparse
import hashlib
from pathlib import Path
import zipfile

EXPECTED_UCD_SHA256 = '2066d1909b2ea93916ce092da1c0ee4808ea3ef8407c94b4f14f5b7eb263d28e'
OUTPUT = Path(__file__).resolve().parents[2] / 'src/text/generated/tibetan_categories.inc'
FIRST, LAST = 0x0F00, 0x0FFF
# Enumerator order of TibetanCategory (src/text/tibetan_character.hpp).
NAMES = ('other', 'base', 'placeholder', 'symbol', 'reserved', 'subjoined', 'cons_above', 'cons_below',
         'vowel_pre', 'vowel_above', 'vowel_below', 'compound', 'vowel_post', 'modifier', 'final', 'split')
SYLLABIC = {
    'Consonant': 'base', 'Consonant_Subjoined': 'subjoined', 'Number': 'placeholder',
    'Consonant_Head_Letter': 'placeholder', 'Avagraha': 'placeholder', 'Nukta': 'cons_above',
    'Bindu': 'modifier', 'Syllable_Modifier': 'final', 'Pure_Killer': 'vowel_below', 'Visarga': 'other',
}
VOWEL_SLOT = {129: 'cons_below', 132: 'vowel_above'}  # other classes: vowel_below


def ranges(text, default):
    values = {}
    for line in text.splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        span, value = (v.strip() for v in line.split(';')[:2])
        lo, _, hi = span.partition('..')
        for cp in range(int(lo, 16), int(hi or lo, 16) + 1):
            if FIRST <= cp <= LAST:
                values[cp] = value
    return [values.get(cp, default) for cp in range(FIRST, LAST + 1)]


def derive(general, syllabic, positional, combining, decomposition):
    """One category name per code point; inputs are per-code-point lists."""
    result = []
    for i in range(LAST - FIRST + 1):
        gc, insc, inpc = general[i], syllabic[i], positional[i]
        if gc == 'Cn':
            value = 'reserved'
        elif insc in SYLLABIC:
            value = SYLLABIC[insc]
        elif insc == 'Vowel_Dependent':
            if inpc == 'Top_And_Bottom':
                value = 'compound' if decomposition[i].startswith('<compat>') else 'split'
            else:
                value = VOWEL_SLOT.get(combining[i], 'vowel_below')
        elif gc == 'Mn':
            value = {'Top': 'modifier', 'Bottom': 'vowel_below'}[inpc]
        elif gc == 'Mc':
            value = {'Left': 'vowel_pre', 'Right': 'vowel_post'}[inpc]
        elif gc == 'Lo':
            value = 'base'
        elif gc == 'So':
            value = 'symbol'
        else:
            value = 'other'
        result.append(value)
    return result


def emit(categories):
    values = [NAMES.index(v) for v in categories]
    packed = [a | b << 4 for a, b in zip(values[::2], values[1::2])]
    lines = ['// Generated by tools/unicode/tibetan_categories.py from Unicode 17.0.0; do not edit.',
             '// Unicode-derived data: Unicode License v3. Copyright (c) 1991-2025 Unicode, Inc.',
             '// See assets/licenses/Unicode-3.0.txt. Two categories per byte.']
    for at in range(0, 128, 8):
        lines.append('    ' + ','.join(f'0x{v:02x}' for v in packed[at:at + 8]) + f', // U+{FIRST + at * 2:04X}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--ucd', required=True, type=Path, help='Unicode 17.0.0 UCD.zip')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    data = args.ucd.read_bytes()
    if hashlib.sha256(data).hexdigest() != EXPECTED_UCD_SHA256:
        raise ValueError('UCD archive does not match the pinned Unicode 17.0.0 release')
    with zipfile.ZipFile(args.ucd) as archive:
        def read(name):
            return archive.read(name).decode('utf-8')
        general = ranges(read('extracted/DerivedGeneralCategory.txt'), 'Cn')
        syllabic = ranges(read('IndicSyllabicCategory.txt'), 'Other')
        positional = ranges(read('IndicPositionalCategory.txt'), 'NA')
        combining = [int(v) for v in ranges(read('extracted/DerivedCombiningClass.txt'), '0')]
        decomposition = [''] * (LAST - FIRST + 1)
        for line in read('UnicodeData.txt').splitlines():
            fields = line.split(';')
            cp = int(fields[0], 16)
            if FIRST <= cp <= LAST:
                decomposition[cp - FIRST] = fields[5]
    args.output.write_bytes(emit(derive(general, syllabic, positional, combining, decomposition)).encode('utf-8'))


if __name__ == '__main__':
    main()
