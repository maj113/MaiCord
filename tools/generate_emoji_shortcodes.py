"""Generate src/ui/emoji_shortcodes.inc from public, permissively licensed emoji data.

Usage: generate_emoji_shortcodes.py UNICODE GEMOJI SHORTCODES OUTPUT

UNICODE    Unicode emoji-test.txt 16.0, or the committed catalog
           src/ui/unicode_emoji_16.inc generated from it (Unicode License v3).
           https://unicode.org/Public/emoji/16.0/emoji-test.txt
GEMOJI     gemoji db/emoji.json (MIT, GitHub, Inc.).
           https://raw.githubusercontent.com/github/gemoji/fadaeaf1f1a9be82b321316a6c5502e43138b2f6/db/emoji.json
SHORTCODES The en/shortcodes directory of emojibase-data 16.0.3 (MIT, Miles
           Johnson): joypixels.json (JoyPixels emoji-toolkit names, MIT),
           iamcal.json (Cal Henderson's emoji-data names, MIT) and
           emojibase.json. https://cdn.jsdelivr.net/npm/emojibase-data@16.0.3/en/shortcodes/

Precedence: joypixels, gemoji, iamcal, emojibase. The first two may shadow a
catalog name (cat is the cat face, as chat users expect); the others only add
names nobody else uses. The catalog's snake_case CLDR names are looked up by
emoji_shortcode_glyph() after this table, so aliases equal to a catalog name
are not repeated. Skin-tone forms (name::skin-tone-N, name_toneN) resolve at
run time from the catalog's Unicode tone sequences; only joypixels tone names
that rule cannot produce (mixed tones, man_tone1_beard) are listed.

Primary names (new favorites/frecency keys) prefer the first [a-z0-9_]
joypixels name, then gemoji's; emoji without a row use their
catalog name, and uniform tone variants their base's name with _toneN.
Standard library only; output is deterministic.
"""
import argparse
import json
from pathlib import Path
import re

from generate_unicode_emoji_catalog import pool_strings, read_canonical_entries, read_entries

ALIAS = re.compile(r'[a-z0-9_+\-]{1,127}')
TONE = re.compile('[\U0001F3FB-\U0001F3FF]')
TONE_SUFFIX = re.compile(r'(.+)(?:::skin-tone-|_tone)([1-5])')


def strip(glyph):
    return glyph.replace('️', '')


def read_catalog(path):
    generated = path.read_text(encoding='utf-8').startswith('// Generated by tools/generate_unicode_emoji_catalog.py')
    entries = read_canonical_entries(path) if generated else read_entries(path)
    return [(name.decode('ascii'), glyph.decode('utf-8')) for name, glyph, _ in entries]


def read_gemoji(path):
    for entry in json.loads(path.read_text(encoding='utf-8')):
        if 'emoji' in entry:  # Entries without a glyph are GitHub-only images.
            yield entry['emoji'], entry['aliases']


def read_preset(path):
    data = json.loads(path.read_text(encoding='utf-8'))
    for hexcode in sorted(data, key=lambda key: [int(part, 16) for part in key.split('-')]):
        names = data[hexcode]
        yield ''.join(chr(int(part, 16)) for part in hexcode.split('-')), [names] if isinstance(names, str) else names


class Catalog:
    def __init__(self, entries):
        self.entries = entries
        self.by_glyph, self.by_name = {}, {}
        for index, (name, glyph) in enumerate(entries):
            self.by_glyph.setdefault(strip(glyph), index)
            self.by_name[name] = index

    def glyph(self, glyph):
        # Fully-qualified catalog bytes; glyphs outside the catalog (keycap *,
        # single regional indicators) are kept as the source spells them.
        index = self.by_glyph.get(strip(glyph))
        return self.entries[index][1] if index is not None else glyph

    def tone_variant(self, base, tone):
        # Mirrors skin_tone_variant() in src/ui/emoji_catalog.cpp.
        index = self.by_glyph.get(strip(base))
        if index is None or TONE.search(base):
            return None
        modifier = chr(0x1F3FA + tone)
        for name, glyph in self.entries[index + 1:]:
            found = TONE.findall(glyph)
            if not found:
                return None
            if set(found) == {modifier} and strip(TONE.sub('', glyph)) == strip(self.entries[index][1]):
                return glyph
        return None


def resolve(catalog, aliases, name):
    # Mirrors emoji_shortcode_glyph(): aliases, catalog names, then tone suffixes.
    def plain(text):
        if text in aliases:
            return aliases[text]
        index = catalog.by_name.get(text)
        return catalog.entries[index][1] if index is not None else None
    glyph = plain(name)
    if glyph is None and (match := TONE_SUFFIX.fullmatch(name)):
        base = plain(match[1])
        glyph = base and catalog.tone_variant(base, int(match[2]))
    return glyph


def collect(catalog, sources):
    # sources: (entries, may_shadow_catalog_names, keep_tones) in precedence order.
    aliases, toned, skipped = {}, [], []
    for source, shadows, tones in sources:
        for glyph, names in source:
            glyph = catalog.glyph(glyph)
            if TONE.search(glyph):
                if tones:
                    toned.extend((name, glyph) for name in names)
                continue
            for name in names:
                if not ALIAS.fullmatch(name):
                    skipped.append(name)
                elif name in catalog.by_name and strip(catalog.entries[catalog.by_name[name]][1]) == strip(glyph):
                    continue
                elif name in catalog.by_name and not shadows:
                    skipped.append(name)
                elif name not in aliases:
                    aliases[name] = glyph
                elif strip(aliases[name]) != strip(glyph):
                    skipped.append(name)
    # Tone names after all plain names, so derivability sees the final table.
    for name, glyph in toned:
        found = resolve(catalog, aliases, name)
        if not ALIAS.fullmatch(name):
            skipped.append(name)
        elif found is None:
            aliases[name] = glyph
        elif strip(found) != strip(glyph):
            skipped.append(name)
    return aliases, skipped


def primary_names(catalog, joypixels, gemoji, aliases):
    first = {}
    for source in (joypixels, gemoji):
        for glyph, names in source:
            # Plain [a-z0-9_] names first: thumbsup over +1, e_mail over e-mail.
            preferred = [name for name in names if re.fullmatch('[a-z0-9_]+', name)] or names
            if preferred:
                first.setdefault(strip(catalog.glyph(glyph)), preferred[0])
    primary = []
    for name, glyph in catalog.entries:
        alias = first.get(strip(glyph))
        # A primary needs a row unless the catalog name or the tone rule
        # (base primary + _toneN) already produces it.
        if alias not in aliases or strip(aliases[alias]) != strip(glyph):
            continue
        if TONE.search(glyph):
            base = strip(TONE.sub('', glyph))
            tones = set(TONE.findall(glyph))
            base_index = catalog.by_glyph.get(base)
            if len(tones) == 1 and base_index is not None:
                base_primary = first.get(base)
                if base_primary not in aliases or strip(aliases[base_primary]) != base:
                    base_primary = catalog.entries[base_index][0]
                if alias == f'{base_primary}_tone{ord(tones.pop()) - 0x1F3FA}':
                    continue
        primary.append(alias)
    return primary


def generate(catalog, gemoji, presets):
    joypixels, iamcal, emojibase = presets
    aliases, skipped = collect(catalog, [(joypixels, True, True), (gemoji, True, False),
                                         (iamcal, False, False), (emojibase, False, False)])
    primary = primary_names(catalog, joypixels, gemoji, aliases)
    glyph_values = [glyph.encode('utf-8') for _, glyph in catalog.entries]
    glyph_values += [glyph.encode('utf-8') for glyph in aliases.values()]
    glyphs, _ = pool_strings(glyph_values, short_first=True)
    ordered = sorted(aliases)
    names, name_offsets = pool_strings([name.encode('ascii') for name in ordered], short_first=True)
    rows = []
    for name, name_offset in zip(ordered, name_offsets):
        glyph = aliases[name].encode('utf-8')
        rows.append((name_offset, glyphs.find(glyph), len(name), len(glyph)))
    if len(glyphs) >= 1 << 16 or len(rows) >= 1 << 16 or max(row[3] for row in rows) >= 256:
        raise ValueError('Shortcode table exceeds its packed field capacity')
    row_of = {name: index for index, name in enumerate(ordered)}
    lines = ['// Generated by tools/generate_emoji_shortcodes.py; do not edit.',
             '// Sources: Unicode emoji-test.txt 16.0 (Unicode License v3), gemoji (MIT) and',
             '// emojibase-data 16.0.3 joypixels, iamcal and emojibase presets (MIT); see the generator.']
    for symbol, pool in [('Names', names), ('Glyphs', glyphs)]:
        lines.append(f'constexpr char kEmojiShortcode{symbol}[] =')
        for start in range(0, len(pool), 48):
            lines.append('    "' + ''.join(chr(b) if symbol == 'Names' and 32 <= b < 127 and b not in (34, 92)
                                         else f'\\{b:03o}' for b in pool[start:start + 48]) + '"')
        lines[-1] += ';'
    lines.append('constexpr EmojiAliasEntry kEmojiShortcodes[] = {')
    lines.extend('    {%d, %d, %d, %d},' % row for row in rows)
    lines.append('};')
    # New favorites/frecency keys, in catalog order; see emoji_shortcode_key().
    lines.append('constexpr u16 kEmojiPrimaryShortcodes[] = {')
    values = [row_of[name] for name in primary]
    for start in range(0, len(values), 16):
        lines.append('    ' + ', '.join(str(row) for row in values[start:start + 16]) + ',')
    lines.append('};')
    summary = (f'{len(rows)} aliases, {len(primary)} primary, {len(names)} name bytes, '
               f'{len(glyphs)} glyph bytes, {len(skipped)} skipped')
    return '\n'.join(lines) + '\n', summary, skipped


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('unicode', type=Path)
    parser.add_argument('gemoji', type=Path)
    parser.add_argument('shortcodes', type=Path, help='emojibase-data en/shortcodes directory')
    parser.add_argument('output', type=Path)
    parser.add_argument('--list-skipped', action='store_true', help='Print aliases left out by the clash rules')
    args = parser.parse_args()
    presets = [list(read_preset(args.shortcodes / f'{name}.json')) for name in ('joypixels', 'iamcal', 'emojibase')]
    text, summary, skipped = generate(Catalog(read_catalog(args.unicode)), list(read_gemoji(args.gemoji)), presets)
    args.output.write_text(text, encoding='utf-8', newline='\n')
    print(summary)
    if args.list_skipped:
        print(' '.join(sorted(set(skipped))))


if __name__ == '__main__':
    main()
