"""Published and independent MLS EncryptWithLabel fixtures/native verification."""
import argparse
import hashlib
import struct
from pathlib import Path
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from hpke_derivation_oracle import load, derive, kem, extract, expand, KEM, schedule

SOURCE_SHA='17cfcf89af9f51d0f2aa7af77f6f9ec99376a039214b6d42a6f11646b83e8c29'
CASES=[(0,0,0),(1,1,1),(55,63,15),(56,64,16),(63,55,17),(64,56,31),(65,65,32),(16375,511,33),(16376,512,256),(16384,16384,1024)]


def pattern(n,factor,add):
    return bytes((i*factor+add)&255 for i in range(n))


def vector(data):
    n=len(data)
    return (bytes([n]) if n<64 else (n|(0x4000 if n<16384 else 0x80000000)).to_bytes(2 if n<16384 else 4,'big'))+data


def info(label,context):
    return vector(b'MLS 1.0 '+label)+vector(context)


def receiver_material(scalar,point,enc,label,context):
    key=ec.derive_private_key(int.from_bytes(scalar,'big'),ec.SECP256R1())
    peer=ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(),enc)
    dh=key.exchange(ec.ECDH(),peer)
    shared=expand(KEM,extract(KEM,b'',b'eae_prk',dh),b'shared_secret',enc+point,32)
    return schedule(shared,info(label,context))


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--vectors',type=Path,required=True)
    parser.add_argument('--verify-native',type=Path)
    args=parser.parse_args()
    v=next(v for v in load(args.vectors,SOURCE_SHA) if v['cipher_suite']==2)['encrypt_with_label']
    scalar,point,enc,context,pt,ct=[bytes.fromhex(v[k]) for k in ['priv','pub','kem_output','context','plaintext','ciphertext']]
    label=v['label'].encode()
    material=receiver_material(scalar,point,enc,label,context)
    assert AESGCM(material[:16]).decrypt(material[16:28],ct,b'')==pt
    if args.verify_native:
        data=args.verify_native.read_bytes();cursor=count=0;encs=set()
        while cursor<len(data):
            assert cursor+81<=len(data)
            enc=data[cursor:cursor+65];nl,nx,np,nc=struct.unpack_from('<IIII',data,cursor+65);cursor+=81
            assert nc==np+16 and cursor+nl+nx+np+nc<=len(data)
            label=data[cursor:cursor+nl];cursor+=nl
            context=data[cursor:cursor+nx];cursor+=nx
            pt=data[cursor:cursor+np];cursor+=np
            ct=data[cursor:cursor+nc];cursor+=nc
            assert enc not in encs;encs.add(enc)
            material=receiver_material(scalar,point,enc,label,context)
            assert AESGCM(material[:16]).encrypt(material[16:28],pt,b'')==ct
            count+=1
        assert count==len(CASES)
        print(f'OpenSSL verified {count} native MLS labeled encryptions with independent framing and distinct encapsulations')
        return
    lines=['// MLSWG cfd450286d1bfd9cd2519b95c80f9771f94a5b1a plus independent Python/OpenSSL vectors.',
        '// Generated by tools/mls_hpke_oracle.py. Published/synthetic test material only.']
    for name,value in [('scalar',scalar),('point',point),('enc',enc),('label',label),('context',context),('pt',pt),('ct',ct)]:
        lines.append(f'constexpr char mls_hpke_{name}[] = "{value.hex()}";')
    lines += ['struct MlsHpkeVector { u32 label, context, plain; const char *enc, *cipher; };','constexpr MlsHpkeVector mls_hpke_vectors[]{']
    for i,(nl,nx,np) in enumerate(CASES):
        l=pattern(nl,7,9);x=pattern(nx,13,5);p=pattern(np,17,3)
        sk,e=derive(hashlib.sha256(f'MaiCord MLS HPKE oracle {i}'.encode()).digest())
        shared=kem(sk,e,point)
        m=schedule(shared,info(l,x));c=AESGCM(m[:16]).encrypt(m[16:28],p,b'')
        assert receiver_material(scalar,point,e,l,x)==m
        lines.append(f'    {{{nl}, {nx}, {np}, "{e.hex()}", "{c.hex()}"}},')
    lines.append('};')
    Path('tests/data/mls_hpke_vectors.hpp').write_text('\n'.join(lines)+'\n',encoding='utf8')
    print(f'published_source_sha256={SOURCE_SHA} independent_ciphertexts={len(CASES)}')


if __name__=='__main__':main()
