#!/usr/bin/env python3
"""Deflate-pack constant tables whose pointers and padding cost more than their text (two tables, one tool).

Usage: pack_tables.py OUTPUT_DIRECTORY PERMISSION_DATA PERMISSION_HEADER PERMISSION_BITS GAME_DATA

Each data file is C++ that a test also compiles as constant data (permission_grid_data.inc, game_data.inc). This tool reads exactly that text (no C++ is compiled) and writes, per table, a generated
`<name>_pack.inc` (counts, sizes and the `#embed` of the zlib stream) that the table's owner inflates on first use
through inflated_block.hpp and walks with PackedReader (core/packed_reader.hpp). A construct this reader
misreads fails the table's pack test instead of shipping.

Streams (a str is its bytes then a NUL; empty means none):
    permission grid: per channel text: str label, description; then per entry: u8 bit number, str label,
        description, u8 channel text + 1 (0 none), u8 group, u8 scopes; then one str per group label
    games: per game: str name, executables
"""
import pathlib
import re
import sys

import pack_settings_catalog as base
from font_reference.embed_fixture import embed_arrays, write_if_changed

fail = base.fail


def tables_of(text, first):
    """name -> parsed initialiser of each `constexpr TYPE NAME[]{...};` from the first `first` on."""
    text = text[text.index(first):]
    text = re.sub(r"^\s*#.*$", "", text, flags=re.M)  # #define / #undef
    text = re.sub(r"channel_text \+ (\d+)", r"channel_text_\1", text)
    return base.parse_statements(text)


def text_of(node):
    if node[0] == "call" and len(node[2]) == 1 and node[2][0][0] == "string":
        return node[2][0][1]
    fail(f"expected a text literal, found {node!r}")


def number_of(node, names=None):
    if node[0] == "number":
        return node[1]
    if node[0] == "or":
        return number_of(node[1], names) | number_of(node[2], names)
    if node[0] == "name" and names and node[1] in names:
        return names[node[1]]
    fail(f"cannot evaluate {node!r}")


def packed(data):
    return base.pack(bytes(data))


def put_text(out, value):
    if b"\0" in value:
        fail("a text holds a NUL")
    out += value + b"\0"


def emit(directory, name, camel, counts, raw):
    """<name>_pack.inc and <name>_packed.bin: the counts the loader sizes its tables with and the stream."""
    directory = pathlib.Path(directory)
    stream = packed(raw)
    write_if_changed(directory / f"{name}_packed.bin", stream)
    lines = ["// Generated by tools/pack_tables.py; do not edit."]
    lines += [f"constexpr u32 k{camel}{label}={value};" for label, value in counts + [("Bytes", len(raw))]]
    lines.append(embed_arrays([(f"constexpr u8 k{camel}Packed[]", f"{name}_packed.bin")]).rstrip("\n"))
    text = "\n".join(lines) + "\n"
    include = directory / f"{name}_pack.inc"
    if not include.exists() or include.read_text() != text:
        include.write_text(text)
    return len(stream)


def permission_grid(directory, data, header, bits):
    tables = tables_of(pathlib.Path(data).read_text(encoding="utf-8"), "constexpr PermissionGridText")
    shifts = {name: int(shift) for name, shift in re.findall(
        r"kPermission(\w+)\s*=\s*1ull\s*<<\s*(\d+)", pathlib.Path(bits).read_text(encoding="utf-8"))}
    groups = base.enumerators(header, "PermissionGroup")
    scope_text = re.search(r"enum PermissionScope : u8 \{(.*?)\};", pathlib.Path(header).read_text(encoding="utf-8"), re.S)
    scopes = {}
    for item in scope_text.group(1).split(","):
        if item.strip():
            name, _, value = (part.strip() for part in item.partition("="))
            shift = re.fullmatch(r"1u\s*<<\s*(\d+)", value)
            scopes[name] = 1 << int(shift[1]) if shift else sum(scopes[part.strip()] for part in value.split("|"))
    letters = {"G": scopes["permission_scope_guild"], "T": scopes["permission_scope_text"],
               "V": scopes["permission_scope_voice"], "S": scopes["permission_scope_stage"],
               "C": scopes["permission_scope_channels"]}
    channel = tables["channel_text"][1]
    out = bytearray()
    for item in channel:
        for field in item[1]:
            put_text(out, text_of(field))
    entries = tables["kEntries"][1]
    for item in entries:
        bit, label, description, channel_ref, group, scope = item[1]
        shift = shifts[bit[1][len("kPermission"):]]
        if channel_ref == ("name", "nullptr"):
            channel_index = 0
        else:
            channel_index = int(channel_ref[1].rpartition("_")[2]) + 1
            if channel_index > len(channel):
                fail("a channel text index is out of range")
        out.append(shift)
        put_text(out, text_of(label))
        put_text(out, text_of(description))
        out += bytes((channel_index, groups[group[1].partition("::")[2]], number_of(scope, letters)))
    labels = tables["kGroupLabels"][1]
    if len(labels) != groups["count"]:
        fail("a group has no label")
    for item in labels:
        put_text(out, text_of(item))
    emit(directory, "permission_grid", "PermissionGrid",
         [("Entries", len(entries)), ("ChannelTexts", len(channel)), ("Groups", len(labels))], out)


def games(directory, data):
    table = tables_of(pathlib.Path(data).read_text(encoding="utf-8"), "constexpr DetectableGame kBuiltin")["kBuiltin"][1]
    out = bytearray()
    for item in table:
        name, executables = item[1]
        put_text(out, text_of(name))
        put_text(out, text_of(executables))
    emit(directory, "game", "Game", [("Count", len(table))], out)


def main():
    directory = pathlib.Path(sys.argv[1])
    directory.mkdir(parents=True, exist_ok=True)
    permission_grid(directory, *sys.argv[2:5])
    games(directory, sys.argv[5])


if __name__ == "__main__":
    main()
