"""Independent OpenSSL-encrypted DAVE receive fixtures (QA dependency only)."""
import ctypes
import hashlib
import sys
from pathlib import Path
try:
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
except ImportError:
    AESGCM = None


class LibcryptoGcm:
    """AES-128-GCM through the libcrypto that ships with CPython (no install)."""

    def __init__(self, key):
        import _ssl  # Loads the interpreter's bundled libcrypto.
        name = 'libcrypto-3-x64.dll' if sys.platform == 'win32' else 'libcrypto.so.3'
        for candidate in (name, 'libcrypto-3.dll'):
            try:
                self.lib = ctypes.CDLL(str(Path(_ssl.__file__).parent / candidate))
                break
            except OSError:
                continue
        lib = self.lib
        lib.EVP_CIPHER_CTX_new.restype = ctypes.c_void_p
        lib.EVP_aes_128_gcm.restype = ctypes.c_void_p
        lib.EVP_EncryptInit_ex.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p,
                                           ctypes.c_char_p, ctypes.c_char_p]
        lib.EVP_EncryptUpdate.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.POINTER(ctypes.c_int),
                                          ctypes.c_char_p, ctypes.c_int]
        lib.EVP_EncryptFinal_ex.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.POINTER(ctypes.c_int)]
        lib.EVP_CIPHER_CTX_ctrl.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_int, ctypes.c_void_p]
        lib.EVP_CIPHER_CTX_free.argtypes = [ctypes.c_void_p]
        self.key = key

    def encrypt(self, iv, plaintext, aad):
        lib = self.lib
        ctx = lib.EVP_CIPHER_CTX_new()
        out = ctypes.create_string_buffer(len(plaintext) + 16)
        tag = ctypes.create_string_buffer(16)
        n = ctypes.c_int(0)
        try:
            assert lib.EVP_EncryptInit_ex(ctx, lib.EVP_aes_128_gcm(), None, self.key, iv) == 1
            if aad:
                assert lib.EVP_EncryptUpdate(ctx, None, ctypes.byref(n), aad, len(aad)) == 1
            assert lib.EVP_EncryptUpdate(ctx, out, ctypes.byref(n), plaintext, len(plaintext)) == 1
            written = n.value
            assert lib.EVP_EncryptFinal_ex(ctx, ctypes.byref(out, written), ctypes.byref(n)) == 1
            assert lib.EVP_CIPHER_CTX_ctrl(ctx, 0x10, 16, tag) == 1  # EVP_CTRL_GCM_GET_TAG
            return out.raw[:written + n.value] + tag.raw
        finally:
            lib.EVP_CIPHER_CTX_free(ctx)


def uleb(value):
    result = bytearray()
    while value >= 128:
        result.append((value & 127) | 128)
        value >>= 7
    return bytes(result + bytes([value]))


def main():
    cases = [
        (0, 0, 0, []), (1, 0, 1, []),
        (10, 0, 127, [(0, 2), (4, 1), (8, 2)]),
        (10, 0, 128, [(0, 10)]), (10, 0, 16383, [(0, 0), (4, 0), (10, 0)]),
        (200, 0, 16384, [(0, 1), (127, 2), (199, 1)]),
        (512, 0, 0xffffff, [(128, 129), (400, 112)]),
        (200, 1, 0, [(0, 40), (40, 160)]),
        (512, 0xffffffff, 0xffffff, []), (512, 0x112, 0x345678, [(0, 512)]),
        (2049, 0x100, 0x4321, [(0, 12), (1200, 16), (2048, 1)]),
        (2049, 0x100, 0x4322, []),
        (64, 0, 5, []), (64, 0, 7, []), (64, 0, 6, []),
    ]
    lines = ['// Generated by tools/dave_frame_crypto_oracle.py using OpenSSL.',
             'struct DaveCryptoVector { const char* key; const char* wire;',
             '    u32 generation, nonce, body_bytes; u8 seed; };',
             'constexpr DaveCryptoVector dave_crypto_vectors[]{']
    digest = hashlib.sha256()
    for case, (size, generation, counter, ranges) in enumerate(cases):
        secret = hashlib.sha256(f'MaiCord synthetic DAVE key {generation}'.encode()).digest()[:16]
        nonce = ((generation & 255) << 24) | counter
        iv = bytes(8) + nonce.to_bytes(4, 'little')
        seed = (case * 17 + 19) & 255
        body = bytes((i * 73 + seed + (i >> 7)) & 255 for i in range(size))
        clear = {i for start, length in ranges for i in range(start, start + length)}
        aad = bytes(v for i, v in enumerate(body) if i in clear)
        plaintext = bytes(v for i, v in enumerate(body) if i not in clear)
        sealed = AESGCM(secret).encrypt(iv, plaintext, aad)
        ciphertext, tag = sealed[:-16], sealed[-16:-8]
        decryptor = Cipher(algorithms.AES(secret), modes.GCM(iv, tag, min_tag_length=8)).decryptor()
        decryptor.authenticate_additional_data(aad)
        assert decryptor.update(ciphertext) + decryptor.finalize() == plaintext
        stream = iter(ciphertext)
        encrypted_body = bytes(v if i in clear else next(stream) for i, v in enumerate(body))
        metadata = uleb(nonce) + b''.join(uleb(start) + uleb(length) for start, length in ranges)
        wire = encrypted_body + tag + metadata + bytes([len(metadata) + 11, 0xfa, 0xfa])
        digest.update(wire)
        lines.append(f'    {{"{secret.hex()}", "{wire.hex()}", {generation}u, {nonce}u, {size}u, {seed}u}},')
    lines.append('};\n')
    target = Path(__file__).resolve().parents[1] / 'tests/data/dave_crypto_vectors.hpp'
    target.write_text('\n'.join(lines), encoding='utf-8')
    print(f'fixtures={len(cases)} concatenated_wire_sha256={digest.hexdigest()}')
    video()


def annex_b_body(size, seed, ranges):
    # Formula bytes with a 4-byte start code opening every clear range of at
    # least five bytes (NAL header ranges); tests rebuild the same body.
    body = bytearray((i * 73 + seed + (i >> 7)) & 255 for i in range(size))
    for start, length in ranges:
        if length >= 5:
            body[start:start + 4] = b'\x00\x00\x00\x01'
    return bytes(body)


def video():
    # Large video frames: only the 8-byte tag comes from OpenSSL; the frame
    # body is a formula, so megabyte fixtures stay small. A matching tag
    # proves the cipher's ciphertext and AAD for the whole frame.
    slices = [(0, 20), (20, 8), (28, 7), (262144, 7), (524288, 7), (786432, 7)]
    dense = [(16384 + 20000 * i, 6) for i in range(60)]
    cases = [
        ('idr_1mib', 1 << 20, 0, 1, slices),
        ('p_frame', 1400, 0, 300, [(0, 7)]),
        ('dense_ranges', 16384 + 20000 * 60, 2, 0x123456, dense),
        ('uhd_4mib_tail', (4 << 20) - 100, 1, 0xfffffe, [(0, 30), (30, 9), (39, 7), ((4 << 20) - 105, 5)]),
    ]
    lines = ['// Generated by tools/dave_frame_crypto_oracle.py using OpenSSL.',
             '// Body: (i * 73 + seed + (i >> 7)) & 255, 00 00 00 01 at each clear range of >= 5 bytes.']
    entries = []
    for name, size, generation, counter, ranges in cases:
        secret = hashlib.sha256(f'MaiCord synthetic DAVE video key {generation}'.encode()).digest()[:16]
        nonce = ((generation & 255) << 24) | counter
        iv = bytes(8) + nonce.to_bytes(4, 'little')
        seed = (size * 7 + generation) & 255
        body = annex_b_body(size, seed, ranges)
        aad = b''.join(body[start:start + length] for start, length in ranges)
        mask = bytearray(size)
        for start, length in ranges:
            mask[start:start + length] = b'\x01' * length
        plaintext = bytes(v for v, m in zip(body, mask) if not m)
        sealed = (AESGCM or LibcryptoGcm)(secret).encrypt(iv, plaintext, aad)
        metadata = uleb(nonce) + b''.join(uleb(start) + uleb(length) for start, length in ranges)
        assert len(metadata) + 11 <= 255, name
        flat = ', '.join(f'{v}u' for start, length in ranges for v in (start, length))
        lines.append(f'constexpr u32 dave_video_ranges_{name}[]{{{flat}}};')
        entries.append(f'    {{"{secret.hex()}", "{sealed[-16:-8].hex()}", dave_video_ranges_{name}, '
                       f'{len(ranges)}u, {size}u, {generation}u, {nonce}u, {seed}u}},')
    lines += ['struct DaveVideoVector { const char* key; const char* tag; const u32* ranges;',
              '    u32 range_count, size, generation, nonce; u8 seed; };',
              'constexpr DaveVideoVector dave_video_vectors[]{'] + entries + ['};\n']
    target = Path(__file__).resolve().parents[1] / 'tests/data/dave_video_vectors.hpp'
    target.write_text('\n'.join(lines), encoding='utf-8')
    print(f'video_fixtures={len(cases)}')


if __name__ == '__main__':
    # "video" regenerates only the large-frame fixtures (libcrypto fallback).
    if 'video' in sys.argv[1:]:
        video()
    else:
        main()
