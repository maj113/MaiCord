"""Build deterministic DAVE framing/partition fixtures (no frame crypto claim)."""
from pathlib import Path


def uleb(value):
    result = bytearray()
    while value >= 128:
        result.append((value & 127) | 128)
        value >>= 7
    result.append(value)
    return bytes(result)


cases = [
    (0, 0, []), (1, 1, []), (10, 127, [(0, 2), (4, 1), (8, 2)]),
    (10, 128, [(0, 10)]), (10, 16383, [(0, 0), (4, 0), (10, 0)]),
    (200, 16384, [(0, 1), (127, 2), (199, 1)]),
    (512, 0xFFFFFF, [(128, 129), (400, 112)]),
    (200, 0x1000000, [(0, 40), (40, 160)]),
    (512, 0xFFFFFFFF, []), (512, 0x12345678, [(0, 512)]),
]
lines = ["// Generated by tools/dave_frame_oracle.py; tag bytes are synthetic.",
         "struct DaveFrameVector { const char* wire; const char* aad; const char* cipher;",
         "    const char* reconstructed; u32 nonce, ranges; };",
         "constexpr DaveFrameVector dave_frames[]{"]
for size, nonce, ranges in cases:
    body = bytes((i * 73 + 19) & 255 for i in range(size))
    clear = {i for start, length in ranges for i in range(start, start + length)}
    aad = bytes(v for i, v in enumerate(body) if i in clear)
    cipher = bytes(v for i, v in enumerate(body) if i not in clear)
    reconstructed = bytes(v if i in clear else v ^ 0xA5 for i, v in enumerate(body))
    supplemental = bytes(range(8)) + uleb(nonce) + b"".join(uleb(o) + uleb(n) for o, n in ranges)
    wire = body + supplemental + bytes([len(supplemental) + 3, 0xFA, 0xFA])
    lines.append(f'    {{"{wire.hex()}", "{aad.hex()}", "{cipher.hex()}", "{reconstructed.hex()}", {nonce}u, {len(ranges)}u}},')
lines.append("};\n")
target = Path(__file__).resolve().parents[1] / "tests/data/dave_frame_vectors.hpp"
target.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {len(cases)} framing fixtures to {target}")
