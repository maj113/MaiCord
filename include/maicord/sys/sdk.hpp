#pragma once

// MaiCord compiles with -nostdinc, without any SDK or compiler header: the
// headers in maicord/sys (C library names in sys/libc) and core/win32_*.hpp
// declare the Windows SDK and compiler symbols it uses, exactly as those
// headers declare them, so the generated code is the same.
//
// MAICORD_SDK_INCLUDES (the conformance unit, reference tools): each of these
// headers first includes the SDK headers it mirrors. Its functions, typedefs
// and macros then redeclare the SDK's, which the compiler checks, and its type
// definitions move into maicord_sdk_mirror, which the asserts generated by
// tools/generate_sys_conformance.py compare with the SDK's.
//
// Type blocks hold nameless unions and structs, as the SDK headers do.
#if defined(MAICORD_SDK_INCLUDES)
#define MAICORD_SYS_TYPES_BEGIN namespace maicord_sdk_mirror {
#define MAICORD_SYS_TYPES_END }
#else
#define MAICORD_SYS_TYPES_BEGIN
#define MAICORD_SYS_TYPES_END
#endif

// A COM vtable slot MaiCord never calls; the conformance asserts check that it
// sits where the SDK's method of that name does.
#define MAICORD_COM_UNUSED(name) virtual void __stdcall unused_##name() = 0
